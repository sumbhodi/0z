;(function () {
  'use strict'

  var APP = window.OZ_APP_CLI; if (!APP) return
  var flag = APP.flag

  // ── prep* — the sheet's data helpers. load, save (the open card hears it), find a topic ──

  function prepDoc() {
    var d = null
    try { d = JSON.parse(localStorage.getItem('toto_prep') || 'null') } catch (_) {}
    if (!d || typeof d !== 'object') {
      d = { discipline: '', date: '', seeing: '', sayFirst: '', scope: [], topics: [], snapshot: [], qa: [], bring: [] }
    }
    ;['scope', 'topics', 'snapshot', 'qa', 'bring'].forEach(function (k) { if (!Array.isArray(d[k])) d[k] = [] })
    return d
  }

  function prepSave(d) {
    try { localStorage.setItem('toto_prep', JSON.stringify(d)) } catch (_) {}
    try { window.dispatchEvent(new CustomEvent('toto-prep-changed')) } catch (_) {}   // an open card re-reads
  }

  function prepTopic(d, ref) {   // a topic by index, by heading, or (no ref) the last one added
    if (ref == null || ref === '') return d.topics[d.topics.length - 1] || null
    if (/^\d+$/.test(String(ref))) return d.topics[+ref] || null
    return d.topics.find(function (t) { return (t.heading || '').toLowerCase() === String(ref).toLowerCase() }) || null
  }

  // ── prepRead — render the sheet back the way the old read_prep did (arrange, never advice) ──

  function prepRead() {
    var d = null
    try { d = JSON.parse(localStorage.getItem('toto_prep') || 'null') } catch (_) {}
    if (!d && window.DEMO_PREP) d = window.DEMO_PREP
    if (!d) return 'ozprep: the clipboard is blank — no session-prep sheet started yet.'

    var L = []
    L.push((d.discipline || 'session') + ' prep' + (d.date ? ' — ' + d.date : '') + (d.seeing ? ' · ' + d.seeing : ''))
    if (d.sayFirst) L.push('say first: ' + d.sayFirst)

    var scope = (d.scope || []).filter(function (r) { return r && r.item })
    if (scope.length) L.push('scope: ' + scope.map(function (r) { return r.item + (r.time ? ' (' + r.time + ')' : '') }).join(' · '))

    ;(d.topics || []).forEach(function (t) {
      if (!t) return
      var bs = (t.bullets || []).filter(Boolean), fs = (t.flags || []).filter(Boolean)
      if (!t.heading && !bs.length && !fs.length) return
      L.push('# ' + (t.heading || '(topic)'))
      bs.forEach(function (b) { L.push('  • ' + b) })
      fs.forEach(function (f) { L.push('  ⚠ ' + f) })
    })

    var snap = (d.snapshot || []).filter(function (r) { return r && r.domain })
    if (snap.length) { L.push('snapshot:'); snap.forEach(function (r) { L.push('  ' + r.domain + ' — ' + (r.rating || '?') + ' — ' + (r.evidence || '')) }) }

    var qa = (d.qa || []).filter(function (r) { return r && r.q })
    if (qa.length) { L.push('if they ask:'); qa.forEach(function (r) { L.push('  Q: ' + r.q + '\n  A: ' + (r.a || '')) }) }

    var bring = (d.bring || []).filter(Boolean)
    if (bring.length) L.push('bring: ' + bring.join(' · '))

    return L.join('\n')
  }

  // ── the twelve subcommands — each is one old bean. positionals for the payload, --flags for the rest ──

  APP.makeApp({
    name: 'ozprep',
    blurb: 'the session-prep sheet — arrange what the patient tells you (never invent findings)',
    clue:
`ozprep — the nurse's session-prep sheet, as a CLI. you ARRANGE what the patient tells you;
you never invent findings, diagnose, or advise. run \`ozprep read\` first to see what's there.
  ozprep read
  ozprep header --discipline LCSW --date "Mar 17" --seeing "the clinic"
  ozprep say-first "the one point to land first"
  ozprep add-scope "what we cover" --time "~5 min"
  ozprep add-topic "Sleep"
  ozprep add-point --topic Sleep "term — the detail in a phrase"
  ozprep add-flag  --topic Sleep "the thing to get on the record"
  ozprep add-snapshot --domain "area" --rating marked --evidence "the one fact"
  ozprep add-qa "the question you expect" "your prepared answer"
  ozprep add-bring "form · letter · or → some-doc.md"
  ozprep save
--topic takes a heading OR an index; omit it and the point/flag lands on the last topic added.`,

    subs: {

      read: function () { return prepRead() },

      header: function (a) {
        var d = prepDoc(), set = []
        ;['discipline', 'date', 'seeing'].forEach(function (k) { if (flag(a, k)) { d[k] = flag(a, k); set.push(k) } })
        if (!set.length) return 'ozprep header: pass --discipline / --date / --seeing.'
        prepSave(d)
        return 'ozprep header — set ' + set.join(' · ') + '.'
      },

      'say-first': function (a) {
        var text = a._.join(' ').trim()
        if (!text) return 'ozprep say-first: pass the one main point (in quotes).'
        var d = prepDoc(); d.sayFirst = text; prepSave(d)
        return 'ozprep say-first — set the main point.'
      },

      'add-scope': function (a) {
        var item = a._.join(' ').trim()
        if (!item) return 'ozprep add-scope: pass the item (in quotes).'
        var d = prepDoc(); d.scope.push({ item: item, time: flag(a, 'time') }); prepSave(d)
        return 'ozprep add-scope — added "' + item + '".'
      },

      'add-topic': function (a) {
        var heading = a._.join(' ').trim()
        if (!heading) return 'ozprep add-topic: pass the heading (in quotes).'
        var d = prepDoc(); d.topics.push({ heading: heading, bullets: [], flags: [] }); prepSave(d)
        return 'ozprep add-topic — added "' + heading + '" (topic ' + (d.topics.length - 1) + ').'
      },

      'add-point': function (a) {
        var text = a._.join(' ').trim()
        if (!text) return 'ozprep add-point: pass the text (in quotes).'
        var d = prepDoc(), t = prepTopic(d, flag(a, 'topic'))
        if (!t) return 'ozprep add-point: no such topic — add a topic first.'
        t.bullets.push(text); prepSave(d)
        return 'ozprep add-point — added under "' + t.heading + '".'
      },

      'add-flag': function (a) {
        var text = a._.join(' ').trim()
        if (!text) return 'ozprep add-flag: pass the text (in quotes).'
        var d = prepDoc(), t = prepTopic(d, flag(a, 'topic'))
        if (!t) return 'ozprep add-flag: no such topic — add a topic first.'
        t.flags.push(text); prepSave(d)
        return 'ozprep add-flag — flagged under "' + t.heading + '".'
      },

      'add-snapshot': function (a) {
        var domain = flag(a, 'domain') || a._.join(' ').trim()
        if (!domain) return 'ozprep add-snapshot: pass --domain (and --rating / --evidence).'
        var d = prepDoc()
        d.snapshot.push({ domain: domain, rating: flag(a, 'rating'), evidence: flag(a, 'evidence') })
        prepSave(d)
        return 'ozprep add-snapshot — added "' + domain + '".'
      },

      'add-qa': function (a) {
        var q = a._[0], ans = a._.slice(1).join(' ')
        if (!q || !String(q).trim()) return 'ozprep add-qa: pass "the question" "the answer".'
        var d = prepDoc(); d.qa.push({ q: String(q), a: String(ans || '') }); prepSave(d)
        return 'ozprep add-qa — added a Q&A.'
      },

      'add-bring': function (a) {
        var text = a._.join(' ').trim()
        if (!text) return 'ozprep add-bring: pass the item (in quotes).'
        var d = prepDoc(); d.bring.push(text); prepSave(d)
        return 'ozprep add-bring — added "' + text + '".'
      },

      save: function () {
        if (typeof window.prepSaveSession !== 'function') {
          return 'ozprep save: open the 📋 prep card once so the clipboard loads, then try again.'
        }
        var label = window.prepSaveSession(prepDoc())
        return 'ozprep save — saved "' + label + '" to the nurse\'s notes (a session tab + a chart note).'
      }

    }
  })

})()
