const extOf = n => (String(n).split('.').pop() || '').toLowerCase()
let lastWrite = null   // the last file written/edited — "preview it" falls back here when the model misremembers the name
const reveal = name => {
  if (window.monacoReveal) { try { window.monacoReveal(name) } catch (_) {} }          // show it in monaco
  if (window.tiptapReveal) { try { window.tiptapReveal(name) } catch (_) {} }           // and in tiptap, if it's the open prose doc
  if (window.previewRefreshFile) { try { window.previewRefreshFile(name) } catch (_) {} }   // re-render it in preview if it's the live tab
}

// the ctx every strike gets — the sandbox + the surfaces, so a strike's source needs nothing from outside.
const TOOL_CTX = {
  // LANE WALL (Sum 2026-07-09) — a bot only SEES its own lane + root + granted mounts; blocked → undefined ("not in sandbox")
  sb:   name => {
    if (window.OZ_ACTOR && window.OZ_LANE && !window.OZ_LANE.canRead(window.OZ_ACTOR, name)) return undefined
    return (window.SANDBOX || {})[name]
  },
  ext:  extOf,
  reveal,
  write(name, content, kind) {
    window.SANDBOX = window.SANDBOX || {}
    // LANE WALL — a bot WRITES only in its own folder; a cross-lane write throws (→ the tool "errors", the bot sees why)
    if (window.OZ_ACTOR && window.OZ_LANE && !window.OZ_LANE.canWrite(window.OZ_ACTOR, name)) {
      throw new Error(`⛔ ${window.OZ_ACTOR} can't write "${name}" outside its lane (${window.OZ_LANE.folder(window.OZ_ACTOR)}/) — cross-lane writes need the 🤖 robot tier`)
    }
    window.SANDBOX[name] = { kind: kind || 'code', ext: extOf(name), mime: '', data: String(content) }
    lastWrite = name; reveal(name)
    try { window.OZ_MAP && window.OZ_MAP.touch(name) } catch (_) {}   // 🗼 keep the jenga tower fresh — every write re-lays this file's arrows
  },
  last: () => lastWrite,
  previewFile(name) {
    if (window.previewSandboxFile && window.previewSandboxFile(name)) return true
    if (window.toggleCard) { window.toggleCard('webview', true); if (window.previewSandboxFile) return !!window.previewSandboxFile(name) }
    return false
  },
}

