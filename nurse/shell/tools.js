// ⭐⭐ `run` and `next` — THE MULTI-PAIR MARKER (Sum 2026-09-01, and it is the fix for a whole class of
//    failure, not one bug): "that is how all small bots fail, all bots really, try and do it all in one
//    pair… like you thinking you have to code everything when we are assembling is same family."
//
//    run: 'speed' | 'search'   — borrowed from MMMM, because those words are already ours.
//      'speed' (the default when unset) — a SPEED RUN. fire it cold, one call, nothing to read first.
//      'search' — a SEARCH RUN. the mouse must read the maze before it moves. An EDIT is the shape:
//                 read the current text, THEN write. It cannot be done in one pair and a bot that tries
//                 will improvise something that looks right and does nothing.
//    next: '…'  — what this tool UNLOCKS, in one line. Handed to the clone WITH the tutorial, so no bot
//                 ever has to hold a chain in working memory: each tool names the link after it.
//                 Sum: "show next step on tool call with tutorial."
//
//    ⚠ CAUGHT LIVE the day this was written: asked to EDIT a snippet, haiku answered "Reading the
//    snippet now, then adding the tell" and emitted a ```read fence — a real fence that only serves
//    sandbox FILES, never a card section. Nothing fired, nothing said so. It was not confused about the
//    task; it was never told the task takes two pairs. Missing tool, not missing brains.
//
//    ⚠ BOTH ARE OPTIONAL AND ALWAYS WILL BE. klass and readback are REFUSED when absent because a bean
//    without them is unsafe. A bean without `run` is merely a speed run, which is the honest default and
//    true of most of the 174. Making this a wall would refuse the whole kit to describe a minority.
//    ⚠ DESTRUCTURED AS `run: runKind` ON PURPOSE — `run` is already the name of this factory's own
//    executor closure further down (`const run = call => …`), and taking the bare name here is a
//    redeclaration that kills the whole file. The BEAN still writes `run: 'search'`; only the local
//    variable is renamed.
window.makeTool = function ({ id, card, blurb, clue, strike, readback, klass, run: runKind, next }) {
  window.TOOLKITS = window.TOOLKITS || { cards: {}, tools: {} }
  window.TOOL_USE = window.TOOL_USE || {}
  // a bean with no id or no strike is not a tool at all — that one IS refused, because registering it
  // would put a name in the map that answers nothing when a bot reaches for it.
  if (!id || !strike) {
    window.OZ_TOOL_DEBT.broken.push(id || '(no id)')
    try { console.error('[makeTool] REFUSED "' + (id || '(no id)') + '" — a bean needs an id and a strike.') } catch (_) {}
    return null
  }
  if (!klass)    { window.OZ_TOOL_DEBT.klass.push(id);    try { console.warn('[makeTool] "' + id + '" declares no klass — the gate is guessing from its NAME. Declare read | write | sharp.') } catch (_) {} }
  if (!readback) { window.OZ_TOOL_DEBT.readback.push(id); try { console.warn('[makeTool] "' + id + '" has no readback — nothing checks that its act actually landed.') } catch (_) {} }
  // ⛔ THE REFUSAL — LIVE as of 2026-08-30. It waited for the debt to reach zero and the debt reached
  //    zero (187 tools · 0 no klass · 0 no readback, read off smoke_test's own readback, not a memory).
  //    Sum's word: "walls in builds are perfect, makes bot think — away from mean, reduce newton's
  //    cradle, increase english." A warning in a console nobody reads is a suggestion; this is the
  //    wall. A tool that skips klass or readback now DOES NOT EXIST, and a missing tool is loud —
  //    the bot that needed it says so out loud, which is the whole point.
  //    ⚠ Returns null and does not throw: every caller ignores the return (checked — all use
  //    `MT({...})`, never `const x = MT(...)`), so a refusal drops that one bean and the rest of the
  //    kit still registers. Recover the old behavior by re-commenting this one line.
  if (!klass || !readback) { console.error('[makeTool] REFUSED "' + id + '" — klass and readback are required.'); return null }

  window.TOOLKITS.tools[id] = { card, blurb }                      // the PICK — card + the main-cue blurb
  let fn, src
  if (typeof strike === 'function') { fn = strike; src = strike.toString() }
  else {
    src = String(strike).trim()
    try { fn = new Function('return (' + src + ')')() } catch (e) { fn = () => `${id}: strike won't compile — ${(e && e.message) || e}` }
  }
  const failed = e => `✗ ${id} FAILED — ${(e && e.message) || e}. the act did NOT happen: tell the human plainly, or fix the call and try once more.`
  const done = (call, out) => {
    // ⭐ THE CARD REPAINTS ON EVERY EDIT, FROM EVERY ROAD (Sum 2026-08-25: "the same mechanisms that show
    //    work on cards from bots should show your work too — any change, card refreshes").
    //    MOVED HERE FROM conductor.js gateRun, where it was born a day earlier. gateRun is the choke point
    //    for the BOT road only: the loopback port fires t.run(call) straight, and so does the CLI and any
    //    UI that reaches a bean. So a human or an outside agent could change a card and the card would sit
    //    there stale — the exact staleness the event was built to kill, just on a different lane.
    //    THIS is the choke point that has no lanes: every road ends at one bean's run(), and run() ends here.
    //    Fires on the ACT, not the save, so a draft built field by field is watchable as it fills; and it
    //    fires before the read-back's early return, because a bean without a read-back still edits a card.
    //    Not on failure — failed() never reaches this, and a failed act has nothing to repaint.
    //    A card with no listener is simply unchanged, so this is safe to fire house-wide.
    try {
      if (card) window.dispatchEvent(new CustomEvent('oz-card-dirty',
        { detail: { card: card, tool: id, by: (typeof window !== 'undefined' && window.OZ_ACTOR) || 'port' } }))
    } catch (_) {}
    if (typeof readback !== 'function') return out
    try { const b = readback(call, out); return b ? String(out == null ? '' : out) + '\n(read-back — the surface itself, not my claim: ' + b + ')' : out }
    catch (_) { return out }
  }
  const run = call => {
    let out
    try { out = fn(call, TOOL_CTX) } catch (e) { return failed(e) }
    if (out && typeof out.then === 'function') return out.then(v => done(call, v), e => failed(e))
    return done(call, out)
  }
  window.TOOL_USE[id] = { clue, run, strike: src, readback, klass: klass || '', card, runKind: runKind === 'search' ? 'search' : 'speed', next: next || '' }   // .clue/.run = the conductor · .clue/.strike = the woodshop edits · .klass = the gate (declared beats the name-regex)
  return id
}


