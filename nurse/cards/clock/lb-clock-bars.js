;(function() {

  // weather-code tables → wx-icons.js (one source, complete WMO set).
  // wx-icons.js loads first on clock.html. (this was a 4th drifted copy.)
  const WX_ICON = window.WX_ICON
  const WX_DESC = window.WX_DESC

  // ── cwEnabled — reads clock-widgets from localStorage ─────

  function cwEnabled(widget) {
    let cw = {}
    try { cw = JSON.parse(localStorage.getItem('clock-widgets') || '{}') } catch {}
    return cw[widget] !== false
  }

  // ── build window.WX from clockBars data ───────────────────

  function buildWX() {
    const b = window.clockBars || {}
    const w = b.weather || {}
    const s = b.sky     || {}
    const a = b.air     || {}

    // D matches the shape lb-weather-*.js expects
    const D = {
      temp:       w.temp,
      code:       w.code,
      isDay:      w.isDay,
      feels:      w.feels,
      humidity:   w.humidity,
      dewpoint:   w.dewpoint,
      wind:       w.wind,
      windDir:    w.windDir,
      windGusts:  w.windGusts,
      pressure:   w.pressure,
      rain:       w.rain,
      precipSum:  w.precipSum,
      cloudcover: w.cloudcover,
      visibility: w.visibility,
      uv:         a.uv   ?? w.uv,
      uvPeakVal:  w.uvPeakVal,
      uvPeakHour: w.uvPeakHour,
      snowNow:    w.snowNow,
      aqi:        a.aqi,
      pm25:       a.pm25,
      pm10:       a.pm10,
      ozone:      a.ozone,
      dust:       a.dust,
      sunrise:    s.sunrise,
      sunset:     s.sunset,
      moonRise:   s.moonRise,
      moonSet:    s.moonSet,
    }

    window.WX = {
      D,
      enabled:  cwEnabled,
      rt:       v => Math.round(v),
      r1:       v => Math.round(v * 10) / 10,
      WX_ICON,
      WX_DESC,
      // the real cardData (lb-weather-cards.js) — pills open the big overlay
      cardData: window.wxCardData,
    }
  }

  // ── renderClockBars — called after each clock fetch ───────
  // (nothing renders — the tiles are static; this just refreshes
  //  window.WX so the overlay reads fresh numbers)

  window.renderClockBars = function renderClockBars() {
    buildWX()
  }

  // ── zone tiles → the big overlay ──────────────────────────
  // the aq-/rs- tiles in the left/right zones ARE the widgets
  // on the clock face — click (or Enter/Space) opens wxOverlay.
  // data-widget names match cardData keys; strays aliased here.
  const TILE_ALIAS = { 'precip-total': 'rain', 'hourly-rain': 'rain', 'sun-arc': 'solar' }

  function wireTiles() {
    document.querySelectorAll('[data-zone="left"] [data-widget], [data-zone="right"] [data-widget]')
      .forEach(el => {
        const w = TILE_ALIAS[el.dataset.widget] || el.dataset.widget
        // `w` is a data-widget key off the clock face, not an agent id — the tile is named
        // "timetravel" because it is the RIDE (lb-timejump wires its click), and the traveler bot
        // may not even be aboard. BIC = light-bar. Both are skipped so wxOverlay never steals a
        // tile that already has an owner. The marker goes on the CODE line, not up here: the leak
        // check reads line by line, so a waiver one line away waives nothing.
        if (w.startsWith('bic-') || w === 'timetravel' || el._wxTile) return   // not-a-bot: a widget key
        el._wxTile = true
        el.style.cursor = 'pointer'
        el.setAttribute('role', 'button')
        el.setAttribute('tabindex', '0')
        const open = () => { if (window._faceDrag) return; if (window.wxOverlay) window.wxOverlay(w, el) }   // a drag is not a click
        el.addEventListener('click', open)
        el.addEventListener('keydown', e => {
          if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); open() }
        })
      })
  }
  wireTiles()

})()
