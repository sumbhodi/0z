;(function () {
  'use strict'

  var APP = window.OZ_APP_CLI; if (!APP) return
  var flag = APP.flag

  // ── ls* — the localStorage helpers, the SAME shape the source beans used (JSON in, JSON out) ──

  function lsGet(k, d) { try { return JSON.parse(localStorage.getItem(k) || d) } catch (_) { return JSON.parse(d) } }
  function lsSet(k, v) { try { localStorage.setItem(k, JSON.stringify(v)) } catch (_) {} }

  // the store keys — one const per surface. do NOT rename: the cards watch these exact keys.

  var SP = 'toto_sleep_profile'          // 🛏️ sleep profile
  var EP = 'toto_exercise_profile'       // 💪 exercise profile
  var EX_DRAFT = 'toto_exercise_draft'   // 💪 exercise draft (build → exercise-save)
  var EX_LOG = 'toto_exercise_log'       // 💪 exercise log (the commit target)
  var SN_DRAFT = 'toto_sleep_night_draft'// 🛏️ sleep-night draft (build → night-save)

  // ── profile* — set ONE field of a {field:value} profile object (overwrites that one field) ──

  function profileSet(key, field, label, id, value) {
    if (value == null || value === '') return id + ': pass --value.'
    var p = lsGet(key, '{}'); p[field] = String(value); lsSet(key, p)
    return id + ': ' + label + ' = "' + value + '".'
  }

  // ── exDraft* — the exercise draft store (a field-by-field workout, exercise-save commits it) ──

  function exGet() { return lsGet(EX_DRAFT, '{}') }
  function exSet(d) { lsSet(EX_DRAFT, d) }
  function exClear() { try { localStorage.removeItem(EX_DRAFT) } catch (_) {} }

  function exInput(id, field, label, value) {
    if (value == null || value === '') return id + ': pass "' + field + '".'
    var dr = exGet(); dr[field] = value; exSet(dr)
    return id + ': draft ' + label + ' = ' + value + '. (exercise-save to commit)'
  }

  // ── snDraft* — the sleep-night draft store (a field-by-field night, night-save commits it) ──

  function snGet() { return lsGet(SN_DRAFT, '{}') }
  function snSet(d) { lsSet(SN_DRAFT, d) }
  function snClear() { try { localStorage.removeItem(SN_DRAFT) } catch (_) {} }

  function snInput(id, field, label, value) {
    if (value == null || value === '') return id + ': pass "' + field + '".'
    var dr = snGet(); dr[field] = value; snSet(dr)
    return id + ': draft night ' + label + ' = ' + value + '. (sleep-night-save to commit)'
  }

  // val(a, key) — a --flag value first, else the positionals (so `set-goal 8` and `--value 8` both work).
  // num(a, key) — the same, coerced to a number (draft numeric fields; matches the source's +c.field || 0).

  function val(a, key) { var f = flag(a, key); return f !== '' ? f : a._.join(' ').trim() }
  function num(a, key) { return +val(a, key) || 0 }

  // ── the subcommands — one per old bean. profiles + two draft families + the sleep read ──

  APP.makeApp({
    name: 'ozwell',
    blurb: 'the sleep + exercise wellness beans — profiles, the workout log, and the night log',
    clue:
`ozwell — the sleep + exercise wellness beans, as a CLI. you ARRANGE what the patient logs;
you never invent a workout or a night's numbers. food is a SEPARATE program (ozfood).
run \`ozwell read\` first to see the sleep nights.
  ozwell read
  ozwell set-goal 8                       (sleep profile: goal · actual · routine · wake · helps · hurts · background)
  ozwell set-actual "5–6 hours most nights"
  ozwell set-routine "warm bath · dim lights by 9pm"
  ozwell set-wake "no alarm when possible"
  ozwell set-helps "hard yoga the day before"
  ozwell set-hurts "eating after 8pm"
  ozwell set-background "clinical insomniac, ADHD"
  ozwell ex-set-favorites "teaching yoga, long walks"    (exercise profile: favorites · frequency)
  ozwell ex-set-frequency "yoga 5×/wk"
  ozwell ex-type "vinyasa yoga"           (exercise draft: type · duration · intensity · date · start)
  ozwell ex-duration 45
  ozwell ex-intensity 3.5                  (MET — walk≈3 · yoga≈3 · run≈8)
  ozwell ex-date 2026-03-27
  ozwell ex-start "10:00 AM"
  ozwell exercise-save                     (needs a type + duration; commits + clears the draft)
  ozwell exercise-clear                    (discard the workout draft)
  ozwell night-date 2026-03-27             (sleep-night draft: date required · inbed · lightsoff · out · awake ·
  ozwell night-inbed 22:30                  onset · deep · rem · light · eff · note)
  ozwell night-lightsoff 23:00
  ozwell night-out 06:30
  ozwell night-awake 20
  ozwell night-onset 15
  ozwell night-deep 90
  ozwell night-rem 110
  ozwell night-light 240
  ozwell night-eff 88
  ozwell night-note "vivid dream"
  ozwell sleep-night-save                  (needs a date; persists via the shared night store)
  ozwell sleep-night-clear                 (discard the night draft)
each set/input takes a positional OR a --value/--<field> flag. numeric fields coerce to a number.`,

    subs: {

      // 🛏️ SLEEP profile (toto_sleep_profile) — one field per subcommand
      'set-goal':       function (a) { return profileSet(SP, 'goal',         'sleep goal (hours/night)',        'set-goal',       val(a, 'value')) },
      'set-actual':     function (a) { return profileSet(SP, 'actual',       'how much sleep you actually get', 'set-actual',     val(a, 'value')) },
      'set-routine':    function (a) { return profileSet(SP, 'onset',        'how you get to sleep (routine)',  'set-routine',    val(a, 'value')) },
      'set-wake':       function (a) { return profileSet(SP, 'wake_routine', 'wake routine',                    'set-wake',       val(a, 'value')) },
      'set-helps':      function (a) { return profileSet(SP, 'helps',        'what helps your sleep',           'set-helps',      val(a, 'value')) },
      'set-hurts':      function (a) { return profileSet(SP, 'hurts',        'what makes sleep worse',          'set-hurts',      val(a, 'value')) },
      'set-background': function (a) { return profileSet(SP, 'background',   'background wellness should know',  'set-background', val(a, 'value')) },

      // 💪 EXERCISE profile (toto_exercise_profile)
      'ex-set-favorites': function (a) { return profileSet(EP, 'favorites', 'movement you actually keep doing', 'ex-set-favorites', val(a, 'value')) },
      'ex-set-frequency': function (a) { return profileSet(EP, 'frequency', 'how often you aim to move',        'ex-set-frequency', val(a, 'value')) },

      // 💪 EXERCISE draft (toto_exercise_draft) — build field by field, exercise-save commits
      'ex-type':      function (a) { return exInput('ex-type',      'type',         'activity (yoga · walk · run · …)',           val(a, 'type')) },
      'ex-duration':  function (a) { return exInput('ex-duration',  'duration_min', 'duration (minutes)',                          num(a, 'duration_min')) },
      'ex-intensity': function (a) { return exInput('ex-intensity', 'met',          'intensity (MET — walk≈3 · yoga≈3 · run≈8)',   num(a, 'met')) },
      'ex-date':      function (a) { return exInput('ex-date',      'date',         'date',                                        val(a, 'date')) },
      'ex-start':     function (a) { return exInput('ex-start',     'start',        'start time',                                  val(a, 'start')) },

      'exercise-save': function () {
        var dr = exGet()
        if (!dr.type || !dr.duration_min) return 'exercise-save: needs a type (ex-type) + duration (ex-duration).'
        var log = lsGet(EX_LOG, '[]')
        log.push({ date: dr.date || new Date().toISOString().slice(0, 10), type: dr.type, start: dr.start || '10:00 AM', duration_min: +dr.duration_min || 0, met: +dr.met || 3.5 })
        lsSet(EX_LOG, log); exClear()
        var kcal = Math.round((+dr.met || 3.5) * 132 * ((+dr.duration_min || 0) / 60))
        return 'exercise-save: logged ' + dr.duration_min + 'min ' + dr.type + ' — ~' + kcal + ' kcal. draft cleared.'
      },

      'exercise-clear': function () { exClear(); return 'exercise-clear: draft discarded.' },

      // 🛏️ SLEEP NIGHT draft (toto_sleep_night_draft) — build field by field, sleep-night-save commits
      'night-date':      function (a) { return snInput('night-date',      'date',      'date (the night — required)',  val(a, 'date')) },
      'night-inbed':     function (a) { return snInput('night-inbed',     'inbed',     'in-bed time',                  val(a, 'inbed')) },
      'night-lightsoff': function (a) { return snInput('night-lightsoff', 'lightsoff', 'lights-off time',              val(a, 'lightsoff')) },
      'night-out':       function (a) { return snInput('night-out',       'outbed',    'out-of-bed time',              val(a, 'outbed')) },
      'night-awake':     function (a) { return snInput('night-awake',     'awake',     'minutes awake in the night',   num(a, 'awake')) },
      'night-onset':     function (a) { return snInput('night-onset',     'onset',     'sleep-onset latency (min)',    num(a, 'onset')) },
      'night-deep':      function (a) { return snInput('night-deep',      'deep',      'deep sleep (min)',             num(a, 'deep')) },
      'night-rem':       function (a) { return snInput('night-rem',       'rem',       'REM sleep (min)',              num(a, 'rem')) },
      'night-light':     function (a) { return snInput('night-light',     'light',     'light sleep (min)',            num(a, 'light')) },
      'night-eff':       function (a) { return snInput('night-eff',       'eff',       'sleep efficiency (%)',         num(a, 'eff')) },
      'night-note':      function (a) { return snInput('night-note',      'note',      'note / dream',                 val(a, 'note')) },

      'sleep-night-save': function () {
        var dr = snGet()
        if (!dr.date) return 'sleep-night-save: needs a date (night-date).'
        if (!window.sleepAddNight) return 'sleep-night-save: the sleep store isn\'t loaded yet.'
        var msg = window.sleepAddNight(dr); snClear()
        return 'sleep-night-save: ' + msg
      },

      'sleep-night-clear': function () { snClear(); return 'sleep-night-clear: discarded.' },

      // 🛏️ the READ — the sleep nights, most recent first (read before you edit)
      read: function () {
        if (!window.sleepNights) return 'read: the sleep store isn\'t loaded yet.'
        var ns = window.sleepNights()
        if (!ns.length) return 'read: no nights logged.'
        return 'sleep nights (recent):\n' + ns.slice(-30).reverse().map(function (n) {
          return '· ' + n.iso + ' eff' + n.eff + '% deep' + n.deep + 'm rem' + n.rem + 'm awake' + n.awake + 'm' + (n.note ? ' — ' + n.note : '')
        }).join('\n')
      }

    }
  })

})()
