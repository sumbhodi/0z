//   · read    → a ▶ run that dry-runs immediately (read + dry-run = zero blast radius)
//   · write/sharp → a ▶ run that goes through window.OZ_CLI.run WITHOUT a bound confirm, so the harness
//                   raises its "super-super-are-you-sure" ozConfirm — the human reads the exact command first.
// Then ↩ feed the transcript back to the bot (bounded by maxHops) so it continues WITH the results.
//
// STILL DRY-RUN: window.OZ_CLI has no real executor installed, so nothing touches the filesystem. This is the
// loop's shape; the real hands (the rust run_cli wall) are deferred to a supervised session. ADDITIVE — edits
// nothing; self-mounts by wrapping runTurn once (idempotent) after it exists.

