// rebuild a LIVE agent bar in place — after its chart/skin was reset, so the look flips live.
// no-op if the agent is toggled OFF (won't sneak it back on). keeps its docked edge + collapse.
window.rebuildAgentIfLive = function (id) {
  if (!bars[id] || !AGENT_BARS[id]) return false
  const old = bars[id], edge = old.dataset.edge, collapsed = old.classList.contains('collapsed'), size = old.style.getPropertyValue('--ab-size')
  old.remove()
  const b = window.makeAgent({ id, ...AGENT_BARS[id] })
  b.dataset.edge = edge
  if (size) b.style.setProperty('--ab-size', size)
  if (collapsed) b.classList.add('collapsed')
  bars[id] = b
  zoneEl(edge).appendChild(b)
  syncSolo()
  return true
}

