// ── the code detector — a chat is for talking, not dumping 200 lines. any ```fence``` in a bubble
//    collapses to ONE line: "▸ code · N lines" + a copy button, expand to read. works for everything. ──
function proseNode(t) { const s = document.createElement('span'); s.textContent = t.replace(/^\n+|\n+$/g, ''); return s }
function codeBar(code) {
  const lines = code.split('\n').length, label = n => `${n} code · ${lines} line${lines > 1 ? 's' : ''}`
  const bar = document.createElement('div'); bar.className = 'code-bar'
  const head = document.createElement('button'); head.className = 'code-head'; head.textContent = label('▸')
  const copy = document.createElement('button'); copy.className = 'code-copy'; copy.title = 'copy'; copy.textContent = '⧉'
  const body = document.createElement('pre'); body.className = 'code-body'; body.textContent = code; body.hidden = true
  head.addEventListener('click', () => { body.hidden = !body.hidden; head.textContent = label(body.hidden ? '▸' : '▾') })
  copy.addEventListener('click', e => { e.stopPropagation(); if (navigator.clipboard) navigator.clipboard.writeText(code); copy.textContent = '✓'; setTimeout(() => copy.textContent = '⧉', 900) })
  bar.append(head, copy, body); return bar
}
function renderWithCode(el, text) {
  text = bleep(text)                            // 🍊 DISPLAY-ONLY grawlix — bleeps "claude"/"anthropic" in the rendered bubble; the engine payload is never touched
  const re = /```([^\n`]*)\r?\n([\s\S]*?)```/g   // [^\n`]* eats the whole info string (incl. a ```name.ext) so it never leaks into the body
  let last = 0, m, any = false
  el.textContent = ''
  while ((m = re.exec(text))) { any = true; if (m.index > last) el.appendChild(proseNode(text.slice(last, m.index))); el.appendChild(codeBar(m[2].replace(/\s+$/, ''))); last = re.lastIndex }
  // an UNCLOSED trailing fence (a truncated reply) — collapse it too, so raw code never spills as "robot speak".
  const open = text.indexOf('```', last)
  if (open >= 0) {
    if (open > last) el.appendChild(proseNode(text.slice(last, open)))
    const after = text.slice(open + 3), nl = after.indexOf('\n')
    el.appendChild(codeBar((nl >= 0 ? after.slice(nl + 1) : after).replace(/\s+$/, '')))
    any = true; last = text.length
  }
  if (!any) { el.textContent = text; return }
  if (last < text.length) el.appendChild(proseNode(text.slice(last)))
}

