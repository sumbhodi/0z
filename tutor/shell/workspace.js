// ── remembered bar geometry — edge · size · collapsed, per agent (the geometry half of the layout) ──
function loadGeo() { try { return JSON.parse(localStorage.getItem('toto_geo') || '{}') || {} } catch (_) { return {} } }
function saveGeo(bar) {
  if (!bar || !bar.dataset.agent) return
  const all = loadGeo()
  all[bar.dataset.agent] = { edge: bar.dataset.edge, size: bar.style.getPropertyValue('--ab-size').trim(), collapsed: bar.classList.contains('collapsed') }
  try { localStorage.setItem('toto_geo', JSON.stringify(all)) } catch (_) {}
}
function applyGeo(bar) {   // paint a freshly-built bar with its remembered edge · size · collapse
  if (!bar || !bar.dataset.agent) return
  const g = loadGeo()[bar.dataset.agent]; if (!g) return
  if (g.edge) bar.dataset.edge = g.edge
  if (g.size) bar.style.setProperty('--ab-size', g.size)
  bar.classList.toggle('collapsed', !!g.collapsed)
}

// ── toggle an agent bar on/off. returns false if id isn't an agent bar ──
window.toggleAgent = function(id, on) {
  if (!AGENT_BARS[id]) return false
  // ⭐ THE PROFILE GATE, 2026-08-30. Sum, on the deployed strip: "coder is still in run it in
  // browser from that same link I hard r" — twice, after the roster filter was live and correct.
  //
  // WHY THE ROSTER FILTER WAS NOT ENOUGH: topbar's applyProfile narrows window.REG.agents, which is
  // what the DRAWER and the GREEN ROOM read. But a wing mounts through THIS function, and this
  // function has only ever asked one question — is there an AGENT_BARS entry? AGENT_BARS is a
  // different map, it lives in this file, and this file loads at index.html:203 while topbar is
  // :157 — so applyProfile cannot filter it even if it wanted to. The bot was gone from every list
  // and still had a working door.
  //
  // ⚠ THE GATE BELONGS HERE, NOT IN THE CALLERS. Seventeen sites call toggleAgent — boot restore, a
  // bar click, a tool, a bot conferring. Guarding callers would be several edits today and one
  // missed next month. One door, one lock.
  var _P = window.OZ_PROFILE
  if (on && _P && _P.agents && _P.agents.indexOf(id) < 0) return false
  if (on && !bars[id]) {
    // build the bar + aim for its remembered HOME — a WING (edge) or the DESK (center) (Sum 2026-07-09)
    const b = window.makeAgent({ id, ...AGENT_BARS[id] })
    bars[id] = b
    applyGeo(b)                                          // restore remembered edge · size · collapse (toggle → last home)
    let edge = b.dataset.edge || AGENT_BARS[id].edge || 'right'
    if (edge === 'center' || edge === 'desk') window.OZ_DOCK.toDesk(b)   // (Sum 2026-07-09) the desk (center stack)
    else window.OZ_DOCK.toWing(b, edge)                                  // a wing — ONE per wing, docked expanded (same path as the drag → no stale-rail bug on reload)
    loadOrder.push(id)
    if (window.OZ_SYS) window.OZ_SYS.wakeFor(id)   // a LOCAL-model bot? ping yocal awake so its RAM read is live
  } else if (!on && bars[id]) {
    bars[id].remove()
    delete bars[id]
    loadOrder = loadOrder.filter(x => x !== id)
  }
  syncSolo()
  return true
}

