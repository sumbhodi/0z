// ── drag the inner handle → how much screen this bar gets ───────────
function wireResize(bar) {
  bar.querySelector('.ab-resize').addEventListener('mousedown', e => {
    e.preventDefault()
    const edge = bar.dataset.edge
    const horizontal = (edge === 'left' || edge === 'right')
    const sign = (edge === 'left' || edge === 'top') ? 1 : -1
    const start = horizontal ? e.clientX : e.clientY
    const startSize = horizontal ? bar.offsetWidth : bar.offsetHeight
    document.body.style.cursor = horizontal ? 'col-resize' : 'row-resize'
    document.body.style.userSelect = 'none'
    document.body.classList.add('resizing')   // kill iframe pointer-events (Ban · Preview) so an open card's iframe can't swallow the drag → mouseup always lands, no stuck slider
    // bars that SHARE a side share the dimension — drag one, resize every bar in the zone,
    // so two bots docked to one edge never drift to different widths.
    const p = bar.parentElement
    const sibs = (p && p.classList.contains('zone')) ? Array.from(p.children) : [bar]
    const min = horizontal ? 280 : 140   // a side-docked bot needs room to READ — never one word per line
    const onMove = ev => {
      const delta = (horizontal ? ev.clientX : ev.clientY) - start
      const max = (horizontal ? window.innerWidth : window.innerHeight) * 0.7
      const size = Math.max(min, Math.min(max, startSize + sign * delta)) + 'px'
      sibs.forEach(b => b.style.setProperty('--ab-size', size))
    }
    const onUp = () => { document.removeEventListener('mousemove', onMove); document.removeEventListener('mouseup', onUp); document.body.style.cursor = ''; document.body.style.userSelect = ''; document.body.classList.remove('resizing'); sibs.forEach(b => saveGeo(b)) }
    document.addEventListener('mousemove', onMove)
    document.addEventListener('mouseup', onUp)
  })
}

