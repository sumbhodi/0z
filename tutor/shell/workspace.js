  const foldTok = foldStart >= 0 ? Math.max(1, Math.round(saved.slice(foldStart, tailStart).reduce((n, m) => n + String(m.content || '').length, 0) / 4)) : 0
  let foldBody = null, work = false
  const isOrder = m => m.role === 'user' && /^```[^\n]*\n[\s\S]*```\s*$/.test(String(m.content || '').trim())
