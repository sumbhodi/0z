//       "## Heading", "- bullet" or a ``` fence got the PUNCTUATION rendered as text, in one run-on
//       line. The model was doing it right; the reader was showing the marks.
//  ⚠ AND THE FIX IS NOT GOFAI. He offered "new line at : or . or before ?" — held on purpose. The
//  bots emit correct structure already; inferring breaks from punctuation would paper over both
//  faults AND fight real formatting. Render what was sent; never guess what was meant.
//
//  ⚠ THE SENTINEL IS  (private use), NOT A NUL. cards/settings/safe.js records why in blood:
//  a literal NUL makes grep treat the WHOLE FILE as binary and return SILENCE instead of an error —
//  a search came back empty and live code was nearly deleted as missing. Never put one in a source.
function mdLite(t) {
  const src = String(t)
  const S = ''
  // fences come out FIRST, so nothing inside a code block is escaped twice or split into paragraphs
  const fences = []
  const held = src.replace(/```[a-z]*\n?([\s\S]*?)```/gi, (_, body) => {
    fences.push(String(body).replace(/\n+$/, ''))
    return S + 'F' + (fences.length - 1) + S
  })
  const blocks = held.split(/\n{2,}/).filter(b => b.trim())
  return blocks.map(b => mdBlock(b, fences, S)).join('')
}

function mdBlock(b, fences, S) {
  const esc = x => String(x).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  const t = b.trim()
  const f = t.match(new RegExp('^' + S + 'F(\\d+)' + S + '$'))
  if (f) return '<pre class="msg-code"><code>' + esc(fences[+f[1]] || '') + '</code></pre>'
  const h = t.match(/^(#{1,4})\s+(.*)$/)
  if (h && t.indexOf('\n') < 0) return '<div class="msg-h msg-h' + h[1].length + '">' + mdInline(h[2]) + '</div>'
  const lines = t.split('\n')
  if (lines.length && lines.every(l => /^\s*[-*•]\s+/.test(l)))
    return '<ul class="msg-ul">' + lines.map(l => '<li>' + mdInline(l.replace(/^\s*[-*•]\s+/, '')) + '</li>').join('') + '</ul>'
  if (lines.length > 1 && lines.every(l => /^\s*\d+[.)]\s+/.test(l)))
    return '<ol class="msg-ol">' + lines.map(l => '<li>' + mdInline(l.replace(/^\s*\d+[.)]\s+/, '')) + '</li>').join('') + '</ol>'
  return '<p class="msg-p">' + mdInline(t) + '</p>'
}

function mdInline(t) {
  return String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>').replace(/\*([^*]+)\*/g, '<i>$1</i>')
    // LINKIFY → THE READER (Sum 2026-07-21: "if user links from cards or bot, capture that sight").
    // A URL in chat becomes a chip that opens the page decluttered in oz (OZ_READER), not a raw
    // navigation that would leave the app. The trailing punctuation is left out of the link.
    .replace(/(https?:\/\/[^\s<]+[^\s<.,;:!?)\]}'"])/g, '<a href="$1" class="oz-readable" target="_blank" rel="noopener" title="read it in 0z">$1 📖</a>')
    // a TRULY-LOCAL video/audio file:// path also opens in the Portal (Sum 2026-07-22: "if it's truly
    // local, give me a local video source"). only media file:// links — kept narrow so paths stay safe.
    .replace(/(file:\/\/\/[^\s<]+\.(?:mp4|webm|ogv|m4v|mov|mp3|m4a|aac|oga|opus|wav|flac|ogg|jpe?g|png|gif|webp|avif|bmp|svg|html?|mhtml))/gi, '<a href="$1" class="oz-readable" title="open it in 0z">▣ $1</a>')
    // `inline code` — the one inline form that was missing, and the one he needs most: an exact
    // string he can select without a whole block. (Sum: "need copy-paste easy buttons just for
    // spellings." He loses ~5% a quiz to transcription, never comprehension.)
    .replace(/`([^`\n]+)`/g, (m, c) => '<code class="msg-tt">' + String(c).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;') + '</code>')
    .replace(/\n/g, '<br>')
}
