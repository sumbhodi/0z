    //    tools and permissions and persona and rules." A difference between bots belongs in the bot's
    //    RECORD, never in the chrome every bot shares. So the name comes from AGENT_DATA and this file
    //    now contains no bot's name at all.
    //    "order slip" stays — it names the SHAPE of the turn (a fenced order), not who received it.
    //    ⚠ STILL A HAND ROLL. Sum, same day: "that should be a bean not a hand roll." foldBar is the maker
    //    and these two lines are a caller hand-fitting labels to it. The proper fix is a fold-bar maker
    //    that takes its label as a parameter the way makeTool takes a clue. Logged in TODO-2026-08-25.md.
    //    This is the mislabel fixed, not the shape fixed.
