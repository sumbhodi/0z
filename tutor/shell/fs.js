    //    resets only ever touch localStorage; this is the one that reaches DISK, and it is deliberately
    //    the separate press because those two facts are not the same fact. Files a human dragged in, a
    //    bot wrote, or a card saved all live in ~/totoII/sandbox and survive every localStorage wipe —
