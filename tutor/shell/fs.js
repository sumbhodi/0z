  function inv(cmd, args) {
    const c = core()
    if (!c || !c.invoke) return Promise.reject(new Error('not in tauri'))
    return c.invoke(cmd, args)
  }
  const NATIVE = !!(window.__TAURI__ && (window.__TAURI__.core || window.__TAURI__.invoke))

  // ── the WEB FLOOR (Sum 2026-08-09, for 0zhub.com: "use better thing then local storage") ──
  // in a browser there is no disk, so IndexedDB is the floor: gigabytes, async, survives reload —
  // localStorage's 5MB wall is what crashed the old web demo on a few large images. same choke
  // points as native (scheduleWrite · hydrate · OZ_FS), so card code never knows which floor it's on.
  // shape copied from TT_STORE (oz-ttscenes.js — the display shelf): open per call, close after
  // every transaction, one explicit promise-wrapped method per verb. same house, same wiring.
  function idb() {
    return new Promise((res, rej) => {
      const r = indexedDB.open('oz-sandbox', 1)
      r.onupgradeneeded = () => { r.result.createObjectStore('files'); r.result.createObjectStore('versions') }
      r.onsuccess = () => res(r.result)
      r.onerror = () => rej(r.error)
    })
  }
  const IDB = {
    async put(store, name, val) {
      const d = await idb()
      return new Promise((res, rej) => {
        const tx = d.transaction(store, 'readwrite')
        tx.objectStore(store).put(val, name)
        tx.oncomplete = () => { d.close(); res() }
        tx.onerror = () => { d.close(); rej(tx.error) }
      })
    },
    async del(store, name) {
      const d = await idb()
      return new Promise((res, rej) => {
        const tx = d.transaction(store, 'readwrite')
        tx.objectStore(store).delete(name)
        tx.oncomplete = () => { d.close(); res() }
        tx.onerror = () => { d.close(); rej(tx.error) }
      })
    },
    async get(store, name) {
      const d = await idb()
      return new Promise((res, rej) => {
        const tx = d.transaction(store, 'readonly')
        const req = tx.objectStore(store).get(name)
        tx.oncomplete = () => { d.close(); res(req.result) }
        tx.onerror = () => { d.close(); rej(tx.error) }
      })
    },
    async all(store) {
      const d = await idb()
      return new Promise((res, rej) => {
        const out = {}
        const tx = d.transaction(store, 'readonly')
        const cur = tx.objectStore(store).openCursor()
        cur.onsuccess = () => { const c = cur.result; if (c) { out[c.key] = c.value; c.continue() } }
        tx.oncomplete = () => { d.close(); res(out) }
        tx.onerror = () => { d.close(); rej(tx.error) }
      })
    },
  }

  // which entries are REAL files we keep on disk. skip the pointers (kind 'url' = a link, 'path' = a file://
  // preview pointer) and data: URLs (images live as data URLs — ephemeral previews, not source files).
  function mirrorable(v) {
    return v && typeof v === 'object' && typeof v.data === 'string'
      && v.kind !== 'url' && v.kind !== 'path'
      && !/^data:/.test(v.data) && v.data.length < 2000000
  }

  // ── the proxy — set mirrors to disk (debounced per file, so a typing-autosave burst is one write);
  //    a DELETE is cache-only (closing a preview tab must NOT erase the file — only the wrecker does, via
  //    OZ_FS.remove). reads pass straight through (default traps), so Object.keys/entries are unchanged. ──
