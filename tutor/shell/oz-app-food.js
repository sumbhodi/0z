;(function () {
  'use strict'

  var APP = window.OZ_APP_CLI; if (!APP) return
  var flag = APP.flag

  // ── food* — the doc helpers. sb reads the sandbox entry; withDoc guards + saves around a mutation ──

  function sb(name) { return (window.SANDBOX || {})[name] }

  function withDoc(fn) {
    var doc = sb('food-plan.json')
    if (!doc || typeof doc.data !== 'string') return 'ozfood: no food doc yet — open the 🥗 food card first.'
    var d
    try { d = JSON.parse(doc.data) } catch (_) { return 'ozfood: the doc is malformed JSON — can\'t edit.' }
    d.pantry = d.pantry || []; d.meals = d.meals || []
    var msg = fn(d)
    doc.data = JSON.stringify(d, null, 2)   // mutate the live entry → the 🥗 food card re-renders itself
    return msg
  }

  function item(d, k) { return d.pantry.find(function (i) { return i.k === k }) }
  function uid(p) { return p + Date.now().toString(36) + Math.floor(Math.random() * 999).toString(36) }

  function svParse(s) {   // "vg:2,pr:1" → { vg: 2, pr: 1 }
    var o = {}
    String(s || '').split(',').forEach(function (p) { var kv = p.split(':'); if (kv[0] && kv[0].trim()) o[kv[0].trim()] = +kv[1] || 0 })
    return o
  }

  // ── foodRead — the pantry + log, the way read_food_doc rendered them (key "name" icon count/max [state]) ──

  function foodRead() {
    var doc = sb('food-plan.json')
    if (!doc || typeof doc.data !== 'string') return 'ozfood: no food doc yet — open the 🥗 food card first (it writes food-plan.json).'
    var d
    try { d = JSON.parse(doc.data) } catch (_) { return 'ozfood: the doc is malformed JSON.' }

    var pantry = (d.pantry || []).map(function (i) {
      return '· ' + i.k + ' "' + i.n + '" ' + (i.icon || '') + ' ' + i.ct + '/' + i.mx + ' [' + i.st + ']' + (i.note ? ' — ' + i.note : '')
    }).join('\n') || '  (empty)'

    var meals = (d.meals || []).map(function (m) {
      return '· ' + (m.id || '?') + ' ' + m.d + ' ' + m.t + ' "' + m.n + '" ' + (m.kcal || 0) + 'kcal P' + (m.p || 0) + '/F' + (m.f || 0) + '/C' + (m.c || 0) + ' [' + (m.status || 'eaten') + ']'
    }).join('\n') || '  (none)'

    return 'food doc — ' + (d.day || '') + ' · goal ' + (d.goal || '?') + ' kcal\n' +
      'PANTRY (key "name" icon count/max [state]):\n' + pantry + '\n' +
      'LOG (id date time "name" macros [status]):\n' + meals
  }

  // ── the subcommands — one per old edit_food_doc op, plus read ──

  APP.makeApp({
    name: 'ozfood',
    blurb: 'the food doc — pantry (item · count · state) + the meal log (macros · servings)',
    clue:
`ozfood — the wellness food doc, as a CLI. run \`ozfood read\` first — it gives each pantry
item's KEY and each meal's id, so you target the right one. always confirm an estimate AS one.
  ozfood read
  ozfood set-count --k chicken --ct 3
  ozfood set-state --k chicken --st ready          (buy · stocked · prepped · ready)
  ozfood set-icon  --k chicken --icon 🍗
  ozfood rename    --k chicken --n "roast chicken"
  ozfood add-item  --n avocado --icon 🥑 --st buy --ct 0 --mx 4
  ozfood log-meal  --n "Caesar salad" --kcal 650 --p 30 --f 40 --c 35 --d 2026-03-27 --t 18:00 --status eaten --sv "vg:2,pr:1"
  ozfood set-meal  --id m3 --status eaten
  ozfood remove-item --k chicken
  ozfood remove-meal --id m3`,

    subs: {

      read: function () { return foodRead() },

      'set-count': function (a) {
        return withDoc(function (d) {
          var i = item(d, flag(a, 'k')); if (!i) return 'ozfood set-count: no item "' + flag(a, 'k') + '".'
          i.ct = Math.max(0, Math.min(i.mx == null ? 99 : i.mx, +flag(a, 'ct') || 0))
          return 'ozfood set-count — ' + i.n + ' → ' + i.ct + '.'
        })
      },

      'set-state': function (a) {
        return withDoc(function (d) {
          var i = item(d, flag(a, 'k')); if (!i) return 'ozfood set-state: no item "' + flag(a, 'k') + '".'
          i.st = flag(a, 'st'); return 'ozfood set-state — ' + i.n + ' → ' + i.st + '.'
        })
      },

      'set-icon': function (a) {
        return withDoc(function (d) {
          var i = item(d, flag(a, 'k')); if (!i) return 'ozfood set-icon: no item "' + flag(a, 'k') + '".'
          i.icon = Array.from(flag(a, 'icon')).slice(0, 3).join(''); return 'ozfood set-icon — ' + i.n + ' ' + i.icon + '.'
        })
      },

      rename: function (a) {
        return withDoc(function (d) {
          var i = item(d, flag(a, 'k')); if (!i) return 'ozfood rename: no item "' + flag(a, 'k') + '".'
          i.n = flag(a, 'n') || i.n; return 'ozfood rename — → ' + i.n + '.'
        })
      },

      'add-item': function (a) {
        return withDoc(function (d) {
          var n = flag(a, 'n') || a._.join(' ').trim(); if (!n) return 'ozfood add-item: pass --n (the name).'
          d.pantry.push({ k: uid('x'), icon: flag(a, 'icon') || '🍴', n: n, u: flag(a, 'u'), ct: +flag(a, 'ct') || 0, mx: +flag(a, 'mx') || 4, st: flag(a, 'st') || 'stocked', note: flag(a, 'note') })
          return 'ozfood add-item — added ' + n + '.'
        })
      },

      'log-meal': function (a) {
        return withDoc(function (d) {
          var n = flag(a, 'n') || a._.join(' ').trim(); if (!n) return 'ozfood log-meal: pass --n (the meal).'
          d.meals.push({ id: uid('m'), d: flag(a, 'd') || d.day, t: flag(a, 't') || 'now', n: n, kcal: +flag(a, 'kcal') || 0, p: +flag(a, 'p') || 0, f: +flag(a, 'f') || 0, c: +flag(a, 'c') || 0, status: flag(a, 'status') || 'eaten', sv: svParse(flag(a, 'sv')), note: flag(a, 'note') })
          return 'ozfood log-meal — logged ' + n + '.'
        })
      },

      'set-meal': function (a) {
        return withDoc(function (d) {
          var m = d.meals.find(function (x) { return x.id === flag(a, 'id') }); if (!m) return 'ozfood set-meal: no meal "' + flag(a, 'id') + '".'
          ;['t', 'n', 'kcal', 'p', 'f', 'c', 'status'].forEach(function (kk) { if (flag(a, kk)) m[kk] = (kk === 'kcal' || kk === 'p' || kk === 'f' || kk === 'c') ? +flag(a, kk) : flag(a, kk) })
          if (flag(a, 'sv')) m.sv = Object.assign({}, m.sv || {}, svParse(flag(a, 'sv')))
          return 'ozfood set-meal — updated meal ' + flag(a, 'id') + '.'
        })
      },

      // the removes food-tools.js had (pantry_remove · meal_remove) — a pantry item by --k, a meal by --id.
      'remove-item': function (a) {
        return withDoc(function (d) {
          var k = flag(a, 'k'), n = d.pantry.length
          d.pantry = d.pantry.filter(function (i) { return i.k !== k })
          return n === d.pantry.length ? 'ozfood remove-item: no item "' + k + '".' : 'ozfood remove-item — removed "' + k + '".'
        })
      },

      'remove-meal': function (a) {
        return withDoc(function (d) {
          var id = flag(a, 'id'), n = d.meals.length
          d.meals = d.meals.filter(function (m) { return m.id !== id })
          return n === d.meals.length ? 'ozfood remove-meal: no meal "' + id + '".' : 'ozfood remove-meal — removed meal "' + id + '".'
        })
      }

    }
  })

})()
