// a labelled field bound to a localStorage key (= one custom-injection section)
function sgField(k, label, ph, rows) {
  const ctrl = rows
    ? `<textarea data-k="${k}" rows="${rows}" placeholder="${ph}">${sgEsc(sgGet(k))}</textarea>`
    : `<input type="text" data-k="${k}" placeholder="${ph}" value="${sgEsc(sgGet(k))}">`
  return `<div class="sg-field"><label>${label}</label>${ctrl}</div>`
}

function sgSelect(k, label, options) {
  const cur = sgGet(k)
  const opts = options.map(o => `<option value="${o}"${o === cur ? ' selected' : ''}>${o}</option>`).join('')
  return `<div class="sg-field"><label>${label}</label><select class="sg-select" data-k="${k}">${opts}</select></div>`
}

// model picker — only the providers you've SAVED a key for (save first, then reopen)
function sgModelField(botId) {
  const allow = window.REG.agentProviders ? window.REG.agentProviders(botId) : null   // jem → ['gemini']
  // noKey providers (yocal · ollama) are keyless BY DESIGN — filtering on a saved key hid every local
  // model from every bot's picker here, while the injection card (which uses REG.availableModels, the
  // one that checks p.noKey) showed them fine. That split is why local looked 'missing' in one place
  // and worked in another. The checkers list below already worked around it by re-adding them by hand.
  let saved = PROVIDERS.filter(p => p.noKey || sgGet('toto_' + p.id + '_key'))
  if (allow) saved = saved.filter(p => allow.includes(p.id))   // google-only bots see only their providers (no local)
  if (!saved.length) return `<div class="sg-field"><label>model</label><div class="sg-dim">add + save a key above to unlock a model.</div></div>`
  const cur = sgGet('toto_bot_' + botId + '_model')
  const groups = saved.map(p =>
    `<optgroup label="${p.name}">${(MODELS[p.id] || []).map(m => `<option value="${m}"${m === cur ? ' selected' : ''}>${m}</option>`).join('')}</optgroup>`).join('')
  return `<div class="sg-field"><label>model</label><select class="sg-select" data-k="toto_bot_${botId}_model">${groups}</select></div>`
}

