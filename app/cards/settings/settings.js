// the HIL location field — auto-detect (📍) or a city search (open-meteo geocoding, free/no key).
// writes oz_geo_manual (sticky) so the almanac uses it; clears the auto-cache so it takes immediately.
function wireLocation(card) {
  const search = card.querySelector('.sg-loc-search')
  if (!search) return
  const results = card.querySelector('.sg-loc-results')
  const current = card.querySelector('.sg-loc-current')
  const refresh = () => { if (window.OZ_CLOCK) window.OZ_CLOCK.refresh() }

  function setLoc(lat, lon, name) {
    sgSet('oz_geo_manual', JSON.stringify({ lat, lon, name }))
    localStorage.removeItem('oz_geo')
    current.textContent = '📍 ' + name
    results.innerHTML = ''; search.value = ''
    refresh()
  }

  // 📍 use my location — drop the manual pick, fall back to auto-detect
  card.querySelector('.sg-loc-here').addEventListener('click', () => {
    localStorage.removeItem('oz_geo_manual'); localStorage.removeItem('oz_geo')
    current.textContent = 'auto-detected from your connection'
    refresh()
  })

  // city search — debounced geocoding (open-meteo, free/no key)
  let t = null
  search.addEventListener('input', () => {
    clearTimeout(t)
    const q = search.value.trim()
    if (q.length < 2) { results.innerHTML = ''; return }
    t = setTimeout(async () => {
      try {
        const r = await fetch(`https://geocoding-api.open-meteo.com/v1/search?name=${encodeURIComponent(q)}&count=5&language=en&format=json`)
        const hits = (await r.json()).results || []
        results.innerHTML = hits.map((p, i) =>
          `<button type="button" class="sg-loc-hit" data-i="${i}">${sgEsc(p.name)}${p.admin1 ? ', ' + sgEsc(p.admin1) : ''} <span class="sg-dim">${sgEsc(p.country_code || '')}</span></button>`).join('')
        results.querySelectorAll('.sg-loc-hit').forEach((b, i) => b.addEventListener('click', () => {
          const p = hits[i]; setLoc(p.latitude, p.longitude, p.name + (p.admin1 ? ', ' + p.admin1 : ''))
        }))
      } catch (_) { results.innerHTML = '<div class="sg-dim">search unavailable</div>' }
    }, 300)
  })
}

