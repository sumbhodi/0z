function wxOvImg(widget, d, cd) {
  const B = window.WX_IMG_BASE || '../../shell/icons/'
  d = d || {}
  const MOON = { '🌑':'moon-new.png','🌒':'moon-waxcres.png','🌓':'moon-firstq.png','🌔':'moon-waxgib.png',
                 '🌕':'moon-full.png','🌖':'moon-wangib.png','🌗':'moon-lastq.png','🌘':'moon-wancres.png' }
  const dec = p => Math.max(10, Math.min(100, Math.round(p/10)*10))
  switch (widget) {
    case 'humidity':   return B+'wx/humidity.png'
    case 'dewpoint':   return B+'wx/dewpoint.png'
    case 'uv': case 'uv-peak': return B+'uv.png'
    case 'rain':       return d.rain > 0 ? B+'wx/overcast-rain-'+dec(d.rain)+'.png' : B+'wx/overcast.png'
    case 'pressure':   return d.pressure == null ? B+'wx/pressure-mid.png'
                            : d.pressure > 1020  ? B+'wx/pressure-high.png'
                            : d.pressure < 1000  ? B+'wx/pressure-low.png' : B+'wx/pressure-mid.png'
    case 'wind': case 'gusts': return B+'wx/windsock.png'
    case 'cloudcover': return d.cloudcover == null ? B+'wx/partly.png'
                            : d.cloudcover < 10 ? B+'wx/mainly-clear.png'
                            : d.cloudcover < 30 ? B+'wx/partly.png'
                            : d.cloudcover < 70 ? B+'wx/mostly-cloudy.png' : B+'wx/overcast.png'
    case 'ozone':      return B+'wx/ozone.png'
    case 'aqi':        return B+'wx/lungs.png'      // the jewel rides beside the number
    case 'visibility': return B+'wx/eyeball.png'
    case 'dust':       return B+'wx/dust.png'       // the sandstorm wall
    case 'pm25':       return d.pm25 == null ? B+'wx/pm25-med.png'
                            : d.pm25 < 12  ? B+'wx/pm25-light.png'
                            : d.pm25 < 35  ? B+'wx/pm25-low.png'
                            : d.pm25 < 55  ? B+'wx/pm25-med.png'
                            : d.pm25 < 150 ? B+'wx/pm25-high.png' : B+'wx/pm25-heavy.png'
    case 'pm10':       return d.pm10 == null ? B+'wx/pm10-med.png'
                            : d.pm10 < 54  ? B+'wx/pm10-light.png'
                            : d.pm10 < 154 ? B+'wx/pm10-low.png'
                            : d.pm10 < 254 ? B+'wx/pm10-med.png'
                            : d.pm10 < 354 ? B+'wx/pm10-high.png' : B+'wx/pm10-heavy.png'
    case 'moon-phase': return cd?.icon && MOON[cd.icon] ? B + MOON[cd.icon] : null
    case 'solar':      return B+'sun.png'
    case 'lunar': {   // tonight's actual phase, same math as cardData
      const days = (Date.now() - new Date('2000-01-06').getTime()) / 86400000
      const idx  = Math.round((days % 29.53) / 29.53 * 8) % 8
      return B + ['moon-new.png','moon-waxcres.png','moon-firstq.png','moon-waxgib.png',
                  'moon-full.png','moon-wangib.png','moon-lastq.png','moon-wancres.png'][idx]
    }
    case 'weather': {  // steal the decile-true png WX_IMG already picks
      const h = window.WX_IMG && window.WX_IMG(d.code, d.rain)
      const m = h && h.match(/src="([^"]+)"/)
      return m ? m[1] : null
    }
  }
  return null   // feels 🌡 · snow-depth ❄️ — emoji reads fine big
}

window.wxOverlay = function wxOverlay(widget, opener) {
  const cd = window.WX?.cardData?.(widget)
  if (!cd?.pairs) return
  const D = window.WX?.D

  let ov = document.getElementById('wx-ov')
  if (!ov) {
    ov = document.createElement('div')
    ov.id = 'wx-ov'
    ov.className = 'wx-ov'
    document.body.appendChild(ov)
    ov.addEventListener('click', e => { if (e.target === ov) window.wxOverlayClose() })
    ov.addEventListener('keydown', e => { if (e.key === 'Escape') { e.stopPropagation(); window.wxOverlayClose() } })
  }

  const img  = wxOvImg(widget, D, cd)
  const head = img ? `<img class="wx-ov-img" src="${img}" alt="">`
                   : `<span class="wx-ov-emoji" aria-hidden="true">${cd.icon || ''}</span>`

  // AQI: the jewel rides WITH the number — color + number, never color alone
  let jewel = ''
  if (widget === 'aqi' && D?.aqi != null) {
    const a = D.aqi
    const c = a<=50?'#22c55e':a<=100?'#eab308':a<=150?'#f97316':a<=200?'#ef4444':'#7c3aed'
    jewel = `<span class="wx-ov-jewel" style="background:${c};box-shadow:0 0 10px ${c}"></span>`
  }

  ov.innerHTML = `
    <div class="wx-ov-card" role="dialog" aria-modal="true" aria-label="${cd.label || widget}" tabindex="-1">
      <button class="wx-ov-x" aria-label="close">✕</button>
      <div class="wx-ov-head">
        ${head}
        <div>
          <div class="wx-ov-value">${cd.value ?? '—'}${jewel}</div>
          <div class="wx-ov-label">${cd.label || ''}${cd.sub ? ' · ' + cd.sub : ''}</div>
        </div>
      </div>
      ${cd.prose ? `<div class="wx-ov-prose">${cd.prose}</div>` : ''}
      <div class="wx-ov-pairs">
        ${cd.pairs.map(p => `<div class="wx-ov-pair"><span class="wx-ov-key">${p.key}</span><span class="wx-ov-val">${p.val}</span></div>`).join('')}
      </div>
      ${cd.tutorial?.length ? `
      <div class="wx-ov-tip">
        <div class="wx-ov-tip-head">ⓘ tip</div>
        ${cd.tutorial.map(t => `<div class="wx-ov-tip-row">${t}</div>`).join('')}
      </div>` : ''}`

  ov.querySelector('.wx-ov-x').addEventListener('click', () => window.wxOverlayClose())
  ov._opener = opener || null
  ov.classList.add('open')
  ov.querySelector('.wx-ov-card').focus()
}

window.wxOverlayClose = function wxOverlayClose() {
  const ov = document.getElementById('wx-ov')
  if (!ov || !ov.classList.contains('open')) return
  ov.classList.remove('open')
  if (ov._opener && document.contains(ov._opener)) ov._opener.focus()
  ov._opener = null
}
