;(function () {
  const TRIPS_KEY = 'tt_trips'
  const MIRROR = u => 'https://api.allorigins.win/raw?url=' + encodeURIComponent(u)
  async function grabJSON(url) {
    const go = async u => { const r = await fetch(u); if (!r.ok) throw new Error(r.status); return r.json() }
    try { return await go(url) } catch { return JSON.parse(await (await fetch(MIRROR(url))).text()) }
  }
  const store = () => { try { return JSON.parse(localStorage.getItem(TRIPS_KEY) || '{}') } catch { return {} } }
  const save = m => { const s = store(); s[m.date] = m; try { localStorage.setItem(TRIPS_KEY, JSON.stringify(s)) } catch {} }

  const MONTHS = ['January','February','March','April','May','June','July','August','September','October','November','December']
  const DAYS = ['Sunday','Monday','Tuesday','Wednesday','Thursday','Friday','Saturday']

  // ── the SPIN — the date flaps roll while the world builds ──
  let spinTimer = null
  function spinStart() {
    // ⚠ RE-ENTRANCY (Sum 2026-08-18: "conductor was too fast, bot was mid ride and
    // interrupted"). A second jump while one is in flight used to overwrite spinTimer and
    // ORPHAN the first interval — still rolling dates every 90ms with no handle left to
    // clear it, so the flaps never settled and only closing the card stopped it. Kill any
    // spin already running before starting another.
    clearInterval(spinTimer); spinTimer = null
    window._ttLock = true
    const day = document.querySelector('#date-row .sf:nth-child(1) .sf-face')
    spinTimer = setInterval(() => {
      const set = (i, v) => document.querySelectorAll('#date-row .sf').forEach((sf, k) => {
        if (k === i) sf.querySelectorAll('.sf-face').forEach(f => f.textContent = v)
      })
      set(0, DAYS[Math.floor(Math.random() * 7)])
      set(1, MONTHS[Math.floor(Math.random() * 12)])
      set(2, String(1 + Math.floor(Math.random() * 28)))
      set(3, String(1800 + Math.floor(Math.random() * 300)))
    }, 90)
  }
  function spinLand(d) {
    clearInterval(spinTimer); spinTimer = null
    const parts = [DAYS[d.getDay()], MONTHS[d.getMonth()], String(d.getDate()), String(d.getFullYear())]
    document.querySelectorAll('#date-row .sf').forEach((sf, k) =>
      sf.querySelectorAll('.sf-face').forEach(f => f.textContent = parts[k]))
  }

  // ── the BUILD — weather · papers · events → one manifest ──
  async function build(dateStr) {
    const d = new Date(dateStr + 'T12:00:00')
    const y = d.getFullYear()
    const now = new Date()
    const future = d > now
    const m = { date: dateStr, built: Date.now(), future, weather: null, papers: [], events: [] }
    const jobs = []

    if (!future && y >= 1940) {
      jobs.push((async () => {
        try {
          const [lat, lon] = window.geo.coords()
          const j = await grabJSON(`https://archive-api.open-meteo.com/v1/archive?latitude=${lat}&longitude=${lon}`
            + `&start_date=${dateStr}&end_date=${dateStr}`
            + `&daily=weather_code,temperature_2m_max,temperature_2m_min,precipitation_sum`
            + `&temperature_unit=fahrenheit&timezone=auto`)
          const dy = j.daily
          if (dy?.time?.length) m.weather = {
            code: dy.weather_code?.[0], hi: dy.temperature_2m_max?.[0],
            lo: dy.temperature_2m_min?.[0], precip: dy.precipitation_sum?.[0],
          }
        } catch (e) { console.warn('[jump] archive weather failed', e) }
      })())
    }

    if (!future && y >= 1789 && y <= 1963) {
      jobs.push((async () => {
        try {
          const mmddyyyy = `${String(d.getMonth() + 1).padStart(2, '0')}${String(d.getDate()).padStart(2, '0')}${y}`
          const j = await grabJSON('https://chroniclingamerica.loc.gov/search/pages/results/'
            + `?date1=${mmddyyyy}&date2=${mmddyyyy}&dateFilterType=range&rows=10&format=json`)
          m.papers = (j.items || []).slice(0, 8).map(it => ({
            paper: (it.title_normal || 'unknown paper').replace(/\.$/, ''),
            place: (it.place_of_publication || '').split(',')[0],
            snippet: (it.ocr_eng || '').replace(/[^\x20-\x7E]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 140),
            link: it.id ? 'https://chroniclingamerica.loc.gov' + it.id : '',
          })).filter(p => p.snippet.length > 30)
        } catch (e) { console.warn('[jump] chronicling failed', e) }
      })())
    }

    if (!future) {
      jobs.push((async () => {
        try {
          const j = await grabJSON(`https://api.wikimedia.org/feed/v1/wikipedia/en/onthisday/events/${d.getMonth() + 1}/${d.getDate()}`)
          const evs = j.events || []
          const exact = evs.filter(e => e.year === y)
          const near = evs.filter(e => Math.abs(e.year - y) <= 20 && e.year !== y).slice(0, 3)
          m.events = [...exact, ...near].slice(0, 5).map(e => ({
            year: e.year, text: e.text, link: e.pages?.[0]?.content_urls?.desktop?.page || '',
          }))
        } catch (e) { console.warn('[jump] onthisday failed', e) }
      })())
    }

    await Promise.allSettled(jobs)
    return m
  }

  // ── the DRESS — every headline bar becomes that morning (Sum 2026-07-20: "turn off
  //    the rest on time travel") — the trip pool is PUBLISHED (window._ttPool) and
  //    lb-headlines swaps its live wires for it while _ttDate is set; the dateless
  //    lanes (kōans · jokes · quotes) ride on. no more stomping bar 1 directly —
  //    that lost to the 20-minute reload anyway, and bars 2/3 leaked the present. ──
  function dress(m) {
    window._ttDate = m.date   // the film strip + shell pokes key off this
    try { localStorage.setItem('tt-last-trip', m.date) } catch (_) {}   // the traveler's now⇄trip toggle reads this (shell, same origin)
    if (window.TT_SCENES) { try { window.TT_SCENES.show(m.date) } catch (_) {} }   // painted frames replace the time
    const pool = []
    m.papers.forEach(p => pool.push({ title: p.snippet + '…', desc: `${p.paper}${p.place ? ' · ' + p.place : ''} — front page, ${m.date} (OCR of the real print)`, link: p.link, src: p.paper.slice(0, 18), credit: 'chroniclingamerica.loc.gov', lane: true }))
    const jumpYear = new Date(m.date + 'T12:00:00').getFullYear()
    // THE WINK (Sum 2026-07-18): events from AFTER the destination stay on the bar,
    // but wear 'later…' — the traveler leaking spoilers on purpose. it's seen 2012.
    m.events.forEach(e => pool.push({ title: `${e.year} — ${e.text}`, desc: e.year > jumpYear ? 'spoilers — the traveler has been past here' : '', link: e.link, src: e.year > jumpYear ? 'later…' : 'this day', credit: 'wikipedia.org', lane: true }))
    if (m.weather) {
      const desc = (window.WX_DESC || {})[m.weather.code] || ''
      pool.push({ title: `that day: high ${Math.round(m.weather.hi)}° · low ${Math.round(m.weather.lo)}°${desc ? ' · ' + desc.toLowerCase() : ''}`, desc: 'real archive weather for this location (open-meteo)', link: '', src: 'weather', credit: '', lane: true })
    }
    // the MORNING EDITION — headlines the traveler typeset when the record ran thin
    ;(m.mock || []).forEach(h => pool.push({ title: h, desc: m.future ? "the morning edition — authored by the traveler from real published trends (the future's still being written)" : 'the morning edition — from the traveler\'s notes (no digitized print reaches this date)', link: '', src: 'morning edition', lane: true }))
    if (!m.papers.length && !(m.mock || []).length) pool.push({ title: 'the morning edition is at the typesetter — the traveler is writing it now', desc: '', link: '', src: m.future ? 'future' : '⏳', lane: true })
    window._ttPool = pool
    if (window.HL_RELOAD) window.HL_RELOAD()
  }

  // the EXIT — a real seated button at the top of the clock, not a floater
  // (Sum 2026-07-18: "I need a way to return to the present, an exit button on clock")
  function chip(m) {
    let c = document.getElementById('tt-chip')
    if (!c) {
      c = document.createElement('button')
      c.id = 'tt-chip'
      c.className = 'tt-home'
      c.innerHTML = '<img class="tt-home-ico" src="clock.png" alt=""><span></span>'
      c.addEventListener('click', () => window.TIME_JUMP.back())
      const zone = document.querySelector('[data-zone="center"]')
      if (zone) zone.insertBefore(c, zone.firstChild)
      else document.body.appendChild(c)
    }
    const d = new Date(m.date + 'T12:00:00')
    c.querySelector('span').textContent = `${MONTHS[d.getMonth()]} ${d.getDate()}, ${d.getFullYear()} — exit to the present`
  }

  // ── the WIDGET (Sum 2026-07-18: "make virtual time travel a widget with traveler icon") —
  //    the skate tile on the face summons the traveler: opens the bar if it's closed or
  //    tucked, and on a fresh arrival it asks the user for a destination. ──
  const go = document.getElementById('tt-go')
  // the gear's "Virtual time travel" toggle — static tile, so it reads its own switch
  try { if (go && JSON.parse(localStorage.getItem('clock-widgets') || '{}').timetravel === false) go.style.display = 'none' } catch (_) {}
  if (go) go.addEventListener('click', () => {
    try {
      const P = window.parent
      const fresh = !(P.agentIsOpen && P.agentIsOpen('timetravel'))
      // the button KNOCKS, the traveler ANSWERS (Sum 2026-07-20: no more puppet bubble —
      // "let the bot know I want to time travel and let it respond naturally"). a real turn
      // through the real pipeline; the persona's RIDE BUTTON block has him pitch a short
      // menu — at least one new road, one revisit off the time map. the echoed line IS
      // what the button said on your behalf — the glass box stays glass. an already-open
      // bar just comes forward (no surprise token spend on a re-press).
      if (fresh && P.ozAskBot) P.ozAskBot('timetravel', '🛼 (the ride button) — take me somewhen.')
      else if (P.ozSummon) P.ozSummon('timetravel')
    } catch (_) {}
  })

  // ── the public machine ──
  window.TIME_JUMP = {
    async jump(dateStr) {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(dateStr)) return 'give me a date as YYYY-MM-DD — the flux hates ambiguity'
      const d = new Date(dateStr + 'T12:00:00')
      if (isNaN(d)) return 'that date does not parse — the flux hates it'
      const saved = store()[dateStr]
      spinStart()
      const minSpin = new Promise(r => setTimeout(r, saved ? 1200 : 2600))   // revisits jump faster — the notes are already written
      const m = saved || await build(dateStr)
      await minSpin
      spinLand(d)
      dress(m)
      chip(m)
      if (!saved) save(m)
      // thin papers → the traveler types the morning edition in the BACKGROUND (the ride
      // never stalls on ink); the bars refresh when it lands, the manifest keeps it forever.
      if (m.papers.length < 3 && !(m.mock || []).length) {
        try {
          const P = window.parent
          if (P && P.TT_PAPERS) P.TT_PAPERS(dateStr, m.future).then(hl => {
            if (hl && hl.length) { m.mock = hl; save(m); if (window._ttDate === m.date) dress(m) }
          }).catch(e => console.warn('[jump] the typesetter jammed', e))
        } catch (_) {}
      }
      try { window.parent && window.parent.TT_TRIPFILE && window.parent.TT_TRIPFILE(dateStr) } catch (_) {}   // trips/<date>/trip.md — the readable manifest
      const w = m.weather ? `weather that day: high ${Math.round(m.weather.hi)}°, low ${Math.round(m.weather.lo)}°.` : (m.future ? 'weather: unwritten.' : 'weather: before the records.')
      const p = m.papers.length ? `${m.papers.length} real front pages on the bar.` : ((m.mock || []).length ? 'the morning edition rides the bar — your own typesetting.' : 'no digitized papers — the morning edition is typesetting in the background.')
      const e = m.events.length ? `${m.events.length} events on file.` : ''
      const sc = (m.scenes || []).length
      const f = sc ? ` ${sc}/4 frames on the strip.` : ' the strip is unpainted — tt_scene puts frames where the time was.'
      return `landed: ${dateStr}${saved ? ' (from the trips folder — no fetches, the notes held)' : ''}. ${w} ${p} ${e}${f} the clock is dressed; the ⏳ chip comes home.`
    },
    back() { location.reload() },   // the present, restored clean
    trips() {
      const s = store()
      const keys = Object.keys(s).sort()
      if (!keys.length) return 'the trips folder is empty — no jumps saved yet.'
      return 'saved trips (revisit any — nearly free):\n' + keys.map(k => {
        const m = s[k]
        return `  ${k} — ${m.papers.length} papers · ${m.events.length} events${m.weather ? ' · weather' : ''}${m.future ? ' · FUTURE' : ''}`
      }).join('\n')
    },
  }
})()
