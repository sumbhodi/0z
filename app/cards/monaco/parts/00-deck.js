    const IMG = /\.(png|jpe?g|gif|webp|bmp|ico)$/i
    const readable = files.filter(f => { const rel = f.webkitRelativePath || f.name; return !SKIP.test(rel) && f.size <= 500 * 1024 && (TEXT.test(rel) || IMG.test(rel)) })
