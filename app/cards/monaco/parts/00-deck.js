  async function saveToDevice() {
    const t = active(); if (!t || !editor) return
    const content = editor.getValue()
    // native: the file already auto-persists to ~/totoII/sandbox; 🏁 EXPORTS A COPY wherever the user picks,
    // via a real save panel through Rust (the webview has neither showSaveFilePicker nor <a download>).
    if (window.OZ_FS && window.OZ_FS.native) {
      const saved = await window.OZ_FS.exportCopy(t.filename, content)
      if (saved) { t.disk = content; pushHistory(t, content) }   // a copy is on disk + a rollback checkpoint
      return
    }
    if (window.showSaveFilePicker) {
      try {
        const h = await showSaveFilePicker({ suggestedName: t.filename })
        const w = await h.createWritable(); await w.write(content); await w.close()
        t.disk = content; pushHistory(t, content)            // 🟢 a copy is now on disk
      } catch (_) { /* the user cancelled the save dialog */ }
    } else {
      const a = document.createElement('a')
      a.href = URL.createObjectURL(new Blob([content], { type: 'text/plain' }))
      a.download = t.filename; a.click(); URL.revokeObjectURL(a.href)
      t.disk = content; pushHistory(t, content)              // 🟢 downloaded → on disk
    }
  }

