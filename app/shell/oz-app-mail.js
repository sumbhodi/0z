;(function () {
  'use strict'

  var APP = window.OZ_APP_CLI; if (!APP) return
  var flag = APP.flag

  // ── draft* — the compose draft, built field-by-field in localStorage, committed by `send` ──

  var DRAFT_KEY = 'toto_email_draft'

  function draftGet() {
    try { return JSON.parse(localStorage.getItem(DRAFT_KEY) || '{}') } catch (_) { return {} }
  }

  function draftSet(d) {
    try { localStorage.setItem(DRAFT_KEY, JSON.stringify(d)) } catch (_) {}
  }

  // short sender name — mirrors email.js shortSender (used by list / search below)

  function shortFrom(from) {
    var m = from && from.match(/^(.+?)\s*</)
    return m ? m[1].replace(/"/g, '') : (from || '')
  }

  // every message the beans can see — the inbox (with overlay) + SENT (from the store)

  function allMsgs() {
    return (window.emailThreads ? window.emailThreads() : []).concat(window.emailSent ? window.emailSent() : [])
  }

  // ── field — one compose field, one write (overwrites that field; build then `send`) ──

  function setField(a, key, label) {
    var v = a._.join(' ').trim()
    if (!v) return 'ozmail: pass the ' + label + ' text (in quotes).'
    var d = draftGet(); d[key] = String(v); draftSet(d)
    return 'ozmail — ' + label + ' = "' + v + '". (draft saved — `ozmail send` to commit.)'
  }

  // ── the thirteen subcommands — one per old bean. positionals carry the payload, --flags the rest ──

  APP.makeApp({
    name: 'ozmail',
    blurb: 'the email card — build a compose draft field-by-field, send it, and triage the inbox',
    clue:
`ozmail — the ✉️ email card, as a CLI. build the compose DRAFT a field at a time, then send it;
or list / read / search / triage the inbox. run \`ozmail list\` to see threads, \`ozmail draft-show\`
to see the draft. send is a real side effect (it commits to SENT) — confirm before you fire it.
  ozmail in-to "maya@stpatrickswellness.com"
  ozmail in-cc "team@ozhunga.com"
  ozmail in-subject "Re: session prep — the template"
  ozmail in-body "Maya — the blank template is attached…"
  ozmail attach-add "session-prep-template.md"        (call again for more)
  ozmail draft-show
  ozmail draft-clear
  ozmail send                                          (commits the draft to SENT; empty → refused)
  ozmail list --tab all                                (all · focused · purchases · junk · sent)
  ozmail read --id 5
  ozmail search "maya"
  ozmail mark-read --id 2
  ozmail trash --id 7`,

    subs: {

      // ── COMPOSE — one field, one bean (overwrites that field; build, then send) ──

      'in-to':      function (a) { return setField(a, 'to', 'recipient (To)') },
      'in-cc':      function (a) { return setField(a, 'cc', 'CC') },
      'in-subject': function (a) { return setField(a, 'subject', 'subject line') },
      'in-body':    function (a) { return setField(a, 'body', 'body text') },

      'attach-add': function (a) {
        var name = a._.join(' ').trim() || flag(a, 'name')
        if (!name) return 'ozmail attach-add: pass a file name.'
        var d = draftGet(); d.attachments = d.attachments || []; d.attachments.push(String(name)); draftSet(d)
        return 'ozmail attach-add — 📎 "' + name + '" (' + d.attachments.length + ' attached).'
      },

      'draft-show': function () {
        var d = draftGet()
        if (!Object.keys(d).length) return 'ozmail draft-show: draft is empty.'
        return 'draft:\n· to: ' + (d.to || '—') + '\n· cc: ' + (d.cc || '—') + '\n· subject: ' + (d.subject || '—') +
          '\n· attachments: ' + ((d.attachments || []).join(', ') || '—') + '\n· body:\n' + (d.body || '—')
      },

      'draft-clear': function () {
        draftSet({})
        return 'ozmail draft-clear: draft discarded.'
      },

      send: function () {
        var d = draftGet()
        if (!(d.subject || '').trim() && !(d.body || '').trim()) {
          return 'ozmail send: nothing to send — set a subject or body first.'
        }
        if (!window.emailSend) return 'ozmail send: the email card isn\'t loaded.'
        var msg = window.emailSend({ to: d.to, cc: d.cc, subject: d.subject, body: d.body, attachments: d.attachments || [] })
        draftSet({})
        return 'ozmail send — ✉️ sent "' + msg.subject + '"' + (d.to ? ' to ' + d.to : '') +
          '. (in SENT — reopen the card to see it.)'
      },

      // ── INBOX — read + triage (reads the same store the card renders) ──

      list: function (a) {
        var inbox = window.emailThreads ? window.emailThreads() : []
        var tab = (flag(a, 'tab') || a._[0] || 'all').toLowerCase()
        var list = inbox.filter(function (t) { return t.labels.indexOf('SPAM') < 0 })
        if (tab === 'sent') list = window.emailSent ? window.emailSent() : []
        else if (tab === 'junk') list = inbox.filter(function (t) { return t.labels.indexOf('SPAM') >= 0 || t.labels.indexOf('CATEGORY_PROMOTIONS') >= 0 })
        else if (tab === 'purchases') list = inbox.filter(function (t) { return t.labels.indexOf('CATEGORY_PURCHASES') >= 0 })
        else if (tab === 'focused') list = inbox.filter(function (t) { return t.labels.indexOf('SPAM') < 0 && t.labels.indexOf('CATEGORY_PROMOTIONS') < 0 && t.labels.indexOf('CATEGORY_PURCHASES') < 0 })
        if (!list.length) return 'ozmail list (' + tab + '): no messages.'
        return 'ozmail list (' + tab + '):\n' + list.map(function (t) {
          return '· #' + t.id + ' ' + (t.unread ? '● ' : '') + shortFrom(t.from) + ' — ' + t.subject
        }).join('\n')
      },

      read: function (a) {
        var id = Number(flag(a, 'id') || a._[0])
        var m = allMsgs().find(function (t) { return t.id === id })
        if (!m) return 'ozmail read: no message #' + (flag(a, 'id') || a._[0]) + '.'
        if (window.emailMark) window.emailMark(id)
        return '#' + m.id + ' — ' + m.subject + '\nfrom: ' + m.from + '\ndate: ' + m.date + '\n' +
          (m.attachments ? 'attachments: ' + m.attachments.join(', ') + '\n' : '') + '\n' + m.body
      },

      search: function (a) {
        var q = String(a._.join(' ') || flag(a, 'query')).toLowerCase()
        if (!q) return 'ozmail search: pass a query.'
        var hits = allMsgs().filter(function (t) { return (t.from + t.subject + (t.snippet || '')).toLowerCase().indexOf(q) >= 0 })
        if (!hits.length) return 'ozmail search "' + q + '": no matches.'
        return 'ozmail search "' + q + '":\n' + hits.map(function (t) {
          return '· #' + t.id + ' ' + shortFrom(t.from) + ' — ' + t.subject
        }).join('\n')
      },

      'mark-read': function (a) {
        if (!window.emailMark) return 'ozmail mark-read: the email card isn\'t loaded.'
        var id = Number(flag(a, 'id') || a._[0])
        window.emailMark(id)
        return 'ozmail mark-read — #' + id + ' marked read.'
      },

      trash: function (a) {
        if (!window.emailTrash) return 'ozmail trash: the email card isn\'t loaded.'
        var id = Number(flag(a, 'id') || a._[0])
        window.emailTrash(id)
        return 'ozmail trash — #' + id + ' moved to trash.'
      }

    }
  })

})()
