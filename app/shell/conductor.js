function parseFence(text, tag) {
  const re = new RegExp('```' + tag + '\\s*([\\s\\S]*?)```', 'gi')
  const out = []
  let m
  while ((m = re.exec(text))) out.push(m[1].trim())
  return out.length ? out.join('\n').trim() : null
}
// how many blocks of this tag the reply actually held — so a caller can tell "one fence" from "three
// fences we glued". Nothing depends on it yet; it is here because the count is what the old bug hid.
function fenceCount(text, tag) {
  const re = new RegExp('```' + tag + '\\s*([\\s\\S]*?)```', 'gi')
  let n = 0
  while (re.exec(text)) n++
  return n
}
