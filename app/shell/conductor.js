// ── confer — a BOT consults another agent and gets the reply BACK (bot→bot), instead of handing the user
//    off. it's the SAME conduct() as a user turn — the requester is just a bot, so: the brief is framed
//    bot-to-bot, the sub-agent's work shows nested + quiet in the caller's stream (glass box), and the reply
//    RETURNS to the caller. THIS is "report back is the same with a bot or a user" — one engine; the path
//    knows which end it's reporting to (bot vs HIL). returns { ok, from, text, error }. ──
window.confer = async function (fromId, toId, brief, ui, signal, chain) {
  if (!toId || !brief) return { error: 'confer needs an agent + a brief' }
  if (!window.conduct) return { error: 'no conductor' }
  // ⭐ CHAIN — THE CYCLE GUARD (2026-08-30, from Gemini's read of the architecture; the catch was
  //    correct and worth acting on). The rank math below permits LATERAL calls (`>=`), and lateral
  //    calls admit a ring: A → B → C → A, all same rank, forever.
  //    Today no such ring can form, but for a reason that lives OUTSIDE this function: only three
  //    bots hold caps:["delegate"] (toto · coder · newsie), so most agents cannot emit a confer at
  //    all. That is a property of the current ROSTER — a json field anyone can add — not of the
  //    code. An invariant nobody can break should not depend on nobody trying.
  //    So the chain is threaded: every agent already on this call stack, refused if seen again.
  //    ⚠ NOT a global in-flight set, deliberately: two unrelated turns conferring the same bot at
  //    once would look identical to a cycle and one would be refused for no reason. The chain is
  //    per-call-stack, so parallel consults of one agent stay legal — only a RING is refused.
  var seen = Array.isArray(chain) ? chain : []
  if (seen.indexOf(toId) >= 0) {
    var ring = seen.concat([toId]).join(' → ')
    if (ui && ui.note) ui.note('\u21bb refused a loop: ' + ring, 'confer')
    return { error: 'loop refused — ' + toId + ' is already on this call chain (' + ring + ')' }
  }
  var onward = seen.concat([fromId])
  // the celestial order — delegation flows DOWN the ranks or laterally within a choir, NEVER up (Sum 2026-07-09).
  if (window.OZ_PERM && window.OZ_PERM.canConfer && !window.OZ_PERM.canConfer(fromId, toId))
    return { error: `${fromId} can't call up to ${toId} — delegation flows down the ranks, not up` }
  ui = ui || consoleUI()
  if (ui.note) ui.note(`🤝 ${fromId} → ${toId}…`, 'confer')
  // the cam shows BOTH halves (Sum 2026-08-12: "can we make it so I see what you said too?") —
  // the brief rides the stream with the same tag, so a consult reads as a conversation, not an echo.
  // (twin of the same edit in SOURCE ~/Local/0z/oz/shell/conductor.js:810 — made in both, not synced.)
  if (ui.note && brief) ui.note(brief, 'confer')
  // a RELAY sink — surface the sub-agent's turns nested in the CALLER's stream, tagged 'confer' (glass box)
  const relay = {
    turn() { const b = ui.turn ? ui.turn('use') : { push() {}, seal() {} }; return { push: c => b.push(c), seal: () => b.seal('confer') } },
    note: (t) => { if (ui.note) ui.note(t, 'confer') },
    openCard: (id) => { if (ui.openCard) ui.openCard(id) },
  }
  const framed = `🤝 You are being consulted by ${fromId} — another agent, NOT the user. Answer concisely and concretely for ${fromId} to use (the spec, the decision, the file — whatever was asked). This is a bot-to-bot consult.\n\n${brief}`
  const res = await window.conduct(toId, framed, relay, signal, 'ai', onward)   // bot-to-bot consult; `onward` carries the chain so the sub-agent cannot call back into it → this prompt is ai-sourced
  return { ok: !(res && res.error), from: toId, text: (res && res.text) || '', error: res && res.error }
}

