    const looksLikeArg = /^[~/.]/.test(arg) || /\//.test(arg) || /\.[A-Za-z0-9]{1,6}$/.test(arg) || /^https?:\/\//i.test(arg)
      || /^(thumbs|columns|glyph|list|preview|icons)$/i.test(arg)
    if (!looksLikeArg) continue
