  // ⚠ 2 Sep 2026 17:00 — Sum: "tutor still landing in monaco. tutor does not have access to write in monaco, only in learn."
  //    This line opened monaco for ANY bot whose plan carried a file block, so the tutor's turns kept surfacing the code
