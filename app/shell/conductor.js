    // ⚠ THE SPLIT CALL (2026-08-16): a bot writes the tool on one line and its argument on the NEXT —
    //   "binary-complex fs_peek" / '{"path": "…"}'. The line scan saw a tool with no argument and the
    //   JSON scan saw an object with no tool, so neither half held a whole call and the turn stalled at
    //   "planning…". If the argument is missing, look down one line.
    if (!rest) { for (let j = li + 1; j < Math.min(li + 3, lines.length); j++) {
      const nxt = String(lines[j] || '').trim()
      if (!nxt || /^```/.test(nxt)) continue
      rest = nxt; li = j; break } }
    if (!rest) { const t0 = resolve(toks[at]); rest = t0 ? borrowedUrl(t0, hint) : '' }   // the borrowed argument (above)
