// the slim run's text → a call object. looseJSON is the small-model repair rail; the goalie below is
// what decides whether the result is fit to run. (Pulled out of runnerBot so the retry shapes the same way.)
function shape(text) {
  const raw = parseFence(text, 'call')
  if (!raw) return null
  try { return JSON.parse(raw) } catch (_) {}
  const loose = looseJSON(raw)
  if (loose) return loose
  // ⭐ 2026-09-01 — THE ONE TAG THE APPEND CANNOT SERVE. parseFence now joins every block of a tag
  //    (Sum: "if unsure append don't overwrite, de-duping is easier than retrieving") and that is right
  //    for the ten LIST tags. ```call is the exception in kind, not in policy: a runner fires ONE tool,
  //    so two call fences join into two objects and no JSON parser can read that — where before the
  //    append it quietly took the first and worked. So nothing is thrown away and nothing regresses:
  //    the join is still tried first (and looseJSON after it), and only if both fail do we fall back to
  //    block one alone — exactly what this did before today.
  const first = String(text).match(new RegExp('```call\\s*([\\s\\S]*?)```', 'i'))
  if (!first) return null
  const one = first[1].trim()
  try { return JSON.parse(one) } catch (_) { return looseJSON(one) }
}
