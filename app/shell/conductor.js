    let at = -1
    for (let k = 0; k < Math.min(toks.length, 6); k++) if (resolve(toks[k])) { at = k; break }   // 6, not 3 (2026-08-23): "The Port Side View feedline_note …" parks the tool at token 5
    if (at < 0) continue
    // ⚠ 1 Sep 2026 — DO NOT RE-JOIN THE TOKENS. The split above eats ':' '=' '(' ',' so a URL came back as
    //    "https //www.youtube.com/watch?v iy4cNTpUu2o" (on tape twice tonight, both yt_transcript strays;
    //    the bean's own regex happened to survive it). The tool token is found by splitting; the ARGUMENT
    //    is the raw remainder of the line after that token, punctuation intact.
    const atIdx = line.indexOf(toks[at])
