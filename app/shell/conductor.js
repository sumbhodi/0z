// ── ② READ — pure JS (no API call): loop the NAMED file(s) through read_file (THE one reader) so the que
//    sees them WITH LINE NUMBERS and can place an add at the right line. OPTIONAL — only the files CHAT
//    asked for (+ what RUN just wrote, on a retry). one reader, one tutorial — no drift with the monaco
//    read_file tool, because it IS that tool. returns { text, names } | null. ──
function readSnapshot(agentId, fileNames) {
  // ⭐ 1 Sep 2026 — a bot with the LEARN card's own reader (class_file_read) may read too; it is
  //    fenced to lessons/ below. Sum: "tutor should not be using monaco" — so the read fence no
  //    longer forces a coder's tool onto a teacher.
  const granted = botData(agentId).tools || []
  const wide = granted.includes('read_file'), narrow = granted.includes('class_file_read')
  if (!wide && !narrow) return null
  if (!fileNames || !fileNames.length) return null
  const sb = window.SANDBOX || {}
  // ⭐ FORGIVING PATHS, 1 Sep 2026 — this was an EXACT key match and it cost a whole turn on the first
  //    unscripted test. Asked for a study sheet, the tutor correctly named "transcripts/double-float.txt";
  //    the sandbox key is "lessons/transcripts/double-float.txt". No match, so the read served nothing,
  //    the que had no file to plan from, asked for the read a second time, and the wrong-fence rescue
  //    turned that into a junk learn_read_profile call. Every step downstream behaved correctly on a
  //    missing file — the file was not missing, the prefix was.
  //    ⚠ A read is the one act where being liberal is free: nothing is written, so a wrong guess costs a
  //    few tokens and a right one saves a round. Exact key first, then a unique suffix match — UNIQUE is
  //    the guard: two files ending the same way is ambiguous and gets skipped rather than guessed.
  const resolve = n => {
    if (sb[n] && typeof sb[n].data === 'string') return n
    const tail = String(n).replace(/^\.?\//, '')
    const hits = Object.keys(sb).filter(k => k === tail || k.endsWith('/' + tail))
    return hits.length === 1 && typeof sb[hits[0]].data === 'string' ? hits[0] : null
  }
  const names = [...new Set(fileNames)].map(resolve).filter(Boolean).filter(n => wide || n.indexOf('lessons/') === 0)   // narrow = lessons/ only
  if (!names.length) return null
  const reader = window.TOOL_USE && window.TOOL_USE.read_file
  if (!reader || !reader.run) return null
  const out = names.map(n => reader.run({ filename: n }))   // ← the one reader: the read_file tool, numbered
  return { text: out.join('\n\n'), names }
}


