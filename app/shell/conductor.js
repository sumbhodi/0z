// looseJSON — a REPAIR rail for a small local model's almost-valid tool call (Sum 2026-07-22: "add more
// rails/linters if they fail; make tools work down to little models"). Runs ONLY after a strict JSON.parse
// throws, so it never touches good JSON. SAFE fixes only (no content-mangling — a write_file body may hold
// apostrophes/braces): strip fence crumbs + any prose before the object, drop trailing commas, and balance
// unclosed braces/brackets. Salvages the call in-place instead of costing another GOFAI other-lane round-trip.
function looseJSON(raw) {
  if (!raw) return null
  let s = String(raw).trim().replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '').trim()
  const first = s.search(/[{[]/); if (first > 0) s = s.slice(first)               // drop prose before the object
  const tries = [s, s.replace(/,\s*([}\]])/g, '$1')]                              // as-is, then trailing-comma stripped
  const stack = []; for (const ch of s) { if (ch === '{' || ch === '[') stack.push(ch === '{' ? '}' : ']'); else if (ch === '}' || ch === ']') stack.pop() }
  if (stack.length) tries.push(s.replace(/,\s*$/, '') + stack.reverse().join(''))  // balance the unclosed braces
  for (const t of tries) { try { const o = JSON.parse(t); if (o && typeof o === 'object') return o } catch (_) {} }
  return null
}
// the ADDS — ```add <filename> <where> blocks: a snippet the main bot composed in the que, placed by JS.
//   where = beginning | end | a line number. INSERT, never splice — so a weak model can't miss.
function parseAdds(text) {
  const adds = []; let m
  const re = /```add[ \t]+([^\n`]+)\r?\n([\s\S]*?)```/gi
  while ((m = re.exec(text))) {
    const head = m[1].trim().split(/\s+/)
    adds.push({ tool: 'add', filename: head[0], where: head.slice(1).join(' ') || 'end', content: m[2].replace(/\s+$/, '') })
  }
  return adds
}
// the REPLACES — ```replace <file> <from> <to> blocks with <<OLD>> / <<NEW>> markers. a surgical swap the
//   main bot lays out after reading; JS fires it. the range pins the match so a weak model can't miss.
function parseReplaces(text) {
  const out = []; let m
  const re = /```replace[ \t]+([^\n`]+)\r?\n([\s\S]*?)```/gi
  while ((m = re.exec(text))) {
    const head = m[1].trim().split(/\s+/)
    const oi = m[2].indexOf('<<OLD>>'), ni = m[2].indexOf('<<NEW>>')
    if (oi < 0 || ni < 0 || ni < oi) continue
    const oldText = m[2].slice(oi + 7, ni).replace(/^\r?\n/, '').replace(/\r?\n[ \t]*$/, '')
    const newText = m[2].slice(ni + 7).replace(/^\r?\n/, '').replace(/\s+$/, '')
    out.push({ tool: 'find_replace', filename: head[0], from: head[1], to: head[2], old: oldText, new: newText })
  }
  return out
}
