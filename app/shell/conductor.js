function streamSink(bubble, hideAt) {
  // ⚠ (Sum 2026-08-16: "keeps getting cut off") — the old line went quiet the moment `full` contained the
  // marker and DROPPED THAT WHOLE CHUNK, so any prose sharing a chunk with the fence opener vanished:
  // "…well, no, I don't exper" + [chunk: "ience time.\n\n```cards…"] → the sentence died mid-word. Bigger
  // chunks lose more, so it got worse the moment a bot moved from haiku to sonnet. Now: push the part of the
  // chunk BEFORE the marker, then go quiet. App-wide — every bot that ends a reply with cards/read/confer.
  const mark = hideAt || '```'
  let full = '', quiet = false
  return {
    chunk(c) {
      if (quiet) { full += c; return }
      const before = full.length
      full += c
      const at = full.indexOf(mark)
      if (at < 0) { bubble.push(c); return }
      quiet = true
      const visible = full.slice(before, at)   // the prose that shared this chunk with the fence — keep it
      if (visible) bubble.push(visible)
    },
    get text() { return full },
  }
}


