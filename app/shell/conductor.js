// ⭐ parsePayloads — 1 Sep 2026. A TOOL ARGUMENT too big for the que line: a snippet body, a lesson,
//    any prose the bot had to COMPOSE. It rides in its own block, named by the step's <what>, and
//    reaches runnerBot as that step's `data`.
//    ⚠ WHY NOT REUSE ```file, WHICH ALREADY DID THIS. It did — `files[ref]` has always been handed to
//    the runner — and I taught the que to use it that way an hour ago. Then the very first live run
//    wrote `~/totoII/sandbox/boolean`, a junk file, and popped monaco open: runPhase writes EVERY file
//    block, because for a file tool the write IS the point. One block was doing two jobs and one of
//    them was wrong. So the payload gets its own name. A file block means "put this on disk"; a
//    payload block means "hand this to the tool". Nothing has to remember which is which.
function parsePayloads(text) {
  // ⚠ NESTING-AWARE, and it has to be (1 Sep 2026). A payload is PROSE THE BOT COMPOSED, and good
  //    teaching prose contains fenced code — the first live payload held a ```java copy block. A plain
  //    non-greedy /```payload …([\s\S]*?)```/ stops at that INNER fence, so the payload arrived cut in
  //    half, mid-sentence, and nothing said so. Same silent-truncation family as parseFence keeping only
  //    the first block: the content is there, the reader is not told it was cut.
  //    So walk lines and count depth instead: ``` with a word after it OPENS, a bare ``` CLOSES.
  const out = {}
  const lines = String(text).split('\n')
  for (let i = 0; i < lines.length; i++) {
    const open = lines[i].match(/^\s*```payload[ \t]+(\S.*)$/i)
    if (!open) continue
    const name = open[1].trim()
    const body = []
    let depth = 1
    for (i++; i < lines.length; i++) {
      const f = lines[i].match(/^\s*```(.*)$/)
      if (f) {
        if (f[1].trim()) depth++            // ```java — an inner block opens
        else if (--depth === 0) break       // a bare ``` closes ours
      }
      body.push(lines[i])
    }
    out[name] = body.join('\n').replace(/\s+$/, '')
  }
  return out
}
