    //    the flag is not the argument. Strip leading --name / --name=value tokens, keep what follows.
    let arg = m[2].trim().replace(/^(?:--?[\w-]+(?:=\S+)?\s+)+/, '').replace(/^--?[\w-]+=(\S+)$/, '$1').replace(/^["'`]|["'`,;)]+$/g, '').trim()
    if (!arg) continue
    if (/^\{/.test(arg)) { try { const j = JSON.parse(arg); out.push({ tool, call: j }); continue } catch (_) {} }
    // it must LOOK like an argument, or prose fires hands: "fs_look at the folder" is a sentence, not a call.
    // ⚠ A BARE FILENAME IS AN ARGUMENT. This guard only took ~ / . or a mode word, so a perfectly formed
    //   que line — "binary-complex fs_peek IMG_0010.HEIC" — resolved to the right tool and was then
    //   THROWN AWAY at the last step, stalling the turn at "planning…". A dotted extension or a slash is
    //   the tell; prose has neither.
    //   ⚠ TAKEN WITHOUT its sibling from 0d774a6, which also re-aimed abs() so a bare name resolved to
