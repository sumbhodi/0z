// oz-verify.js — HILLICINOT FOR CODE (Sum 2026-07-27: "what gemma local does for words, for code").
//
// THE WHOLE IDEA: the word-checker needs a MODEL, because "is this claim verifiable?" is a judgment
// call. A code claim isn't. "I wrote perm-fix.js" is `test -f`. "It parses" is a syntax check. "63
// lines" is a count. So this checker is GOFAI — deterministic, instant, free, and with no false
// positives (it never flags a metaphor, because it only ever looks at things that are literally true
// or literally not). It is strictly cheaper AND stricter than asking a model to review the same claim.
//
// WHY IT EXISTS (the night that earned it, 2026-07-27): a bot said "all three files are on disk,
// ready — apply them to the live app" and TWO OF THE THREE DID NOT EXIST. Twice. It wasn't lying; it
// genuinely could not tell SHOWING a code block from SAVING one. No agent has privileged access to its
// own process — every "I did X" is a hypothesis, not a report. This turns the hypothesis into a fact
// before it reaches the human.
//
// USED BY: the SAY road (shell/links.js) after each tool turn, engineSelfCheck (shell/engine.js)
// as the FREE first pass — a hard disk failure returns without ever spending a model call — and since
// 2026-08-16 the CONDUCTOR's chat road (verifyPass, shell/conductor.js), so an ordinary chat turn is
// audited too; it was not, and that is how a false 'showing it to you now' reached the human.

