function mountSkinSeat(bar) {
  const slot = document.createElement('span'); slot.className = 'tb-skinseat'
  const paint = () => {
    slot.innerHTML = ''
    const R = window.REG; if (!R || !R.houseFor) return
    const id = R.houseFor(document.documentElement.dataset.skin || 'oz')
    if (!id || id === R.houseFor('oz')) return              // the default house bot already has the collar
    const allowed = window.OZ_PROFILE && window.OZ_PROFILE.agents
    if (allowed && !allowed.includes(id)) return            // ⭐ the paid gate, re-asserted
    const a = (window.AGENT_DATA && window.AGENT_DATA[id]) || {}, ic = a.icon || {}
    slot.appendChild(makeToggle({ id, css: ic.css, cssRef: ic.cssRef, img: ic.img,
      emoji: ic.emoji || '●', label: (a.name || id) + " — this skin's bot" }))
  }
  paint(); bar.appendChild(slot)
  window.addEventListener('skinchange', paint)
}

