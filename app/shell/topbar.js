  // AUTOSCROLLS itself — at boot, and again whenever a reply paints — and each one is a big
  // downward delta from nobody. An arm-late timer lost the same race an hour later. The honest
  // discriminator: a scroll only speaks for the human if a TOUCH or a WHEEL happened just before
  // it — machinery never touches and never spins a wheel. (Wheel joined touch when the feature
  // was PROMOTED TO EVERY SIZE — Sum, on his desktop: "I want that feature even in landscape";
  // the phone gate below went with it. A scrollbar drag stays undetected → the chrome stays,
  // which is the harmless side. Keyboard scrolls keep the chrome via the keydown door below.)
  let lastHuman = 0
  const human = () => { lastHuman = Date.now() }
  window.addEventListener('touchstart', human, { passive: true })
  window.addEventListener('touchmove', human, { passive: true })
  // ⭐ 2 Sep 2026 — THE GESTURE DOOR (Sum, iPhone: "if there is not a box on the screen to scroll, like in arcade, autohide
  //    still won't hide"). Everything above judges SCROLL events, and a screen whose content fits — the arcade, a collapsed
  //    desk, a short chat — never fires one. So the finger itself is read: a touch that moves up more than 28px without any
  //    scroller answering it is the same 'pull the content up' intent, and a drag down of 12px the same 'give me the bar'.
  //    The moment a real scroller moves under the finger (`gesture.scrolled`, set by the judge above the instant it judges
  //    a human scroll), this door steps aside for that gesture — the two never disagree, they only take turns. Touches that
  //    start on the bars themselves (the top bar scrolls sideways now) or in a text field are not gestures.
  const gesture = { y: null, scrolled: false }
  const gStart = y => { gesture.y = y; gesture.scrolled = false }
  const gMove = y => {
    if (gesture.y == null || gesture.scrolled) return
    const dy = y - gesture.y
    if (dy < -28) { gesture.y = y; set(true) }         // finger up = pulling the content up = room
    else if (dy > 12) { gesture.y = y; set(false) }    // finger down = the bar
  }
  const gEnd = () => { gesture.y = null }
