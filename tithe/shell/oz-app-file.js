;(function () {
  'use strict'

  var APP = window.OZ_APP_CLI; if (!APP) return
  var flag = APP.flag

  // ── file* — the sandbox helpers, mirroring shell/tools.js TOOL_CTX (so a card sees writes live) ──

  var lastWrite = null

  function extOf(n) { return (String(n).split('.').pop() || '').toLowerCase() }
  function sb(name) { return (window.SANDBOX || {})[name] }

  function reveal(name) {
    if (window.monacoReveal) { try { window.monacoReveal(name) } catch (_) {} }
    if (window.tiptapReveal) { try { window.tiptapReveal(name) } catch (_) {} }
    if (window.previewRefreshFile) { try { window.previewRefreshFile(name) } catch (_) {} }
  }

  function fileWrite(name, content, kind) {
    window.SANDBOX = window.SANDBOX || {}
    window.SANDBOX[name] = { kind: kind || 'code', ext: extOf(name), mime: '', data: String(content) }
    lastWrite = name; reveal(name)
  }

  function previewFile(name) {
    if (window.previewSandboxFile && window.previewSandboxFile(name)) return true
    if (window.toggleCard) { window.toggleCard('webview', true); if (window.previewSandboxFile) return !!window.previewSandboxFile(name) }
    return false
  }

  // the payload text after the file name — the rest of the positionals, rejoined (quote it to keep it whole).
  function rest(a) { return a._.slice(1).join(' ') }

  // ── the subcommands — one per file bean, on window.SANDBOX ──

  APP.makeApp({
    name: 'ozfile',
    blurb: 'the sandbox files as CLI — read/list/new/write/add/edit/template/preview (runs in-page, any browser)',
    clue:
`ozfile — the sandbox files, as a CLI that runs IN THE APP (works in the browser, no native shell needed).
For a WHOLE-FILE body use a HEREDOC — the marker fences it, so nothing inside needs escaping (a short one-liner
can still ride in "quotes", but a stray " or a newline breaks that; the heredoc never does):
  ozfile write page.html <<'EOF'
  <!DOCTYPE html> … the entire file, verbatim … </html>
  EOF
  ozfile list [dir]                         (ls the sandbox; dir = a path prefix like "code")
  ozfile read index.html                    (comes back WITH line numbers)
  ozfile new page.html                      (a blank/starter file — content is a separate step)
  ozfile write snake.html <<'EOF' … EOF     (or "…" for a short body)
  ozfile add page.html --where end <<'EOF' … EOF   (--where beginning | end | a line NUMBER)
  ozfile edit clock.js --old "old text" --new "new text" [--from 78 --to 82]   (surgical splice)
  ozfile template snake                      (open a ready-made template)
  ozfile preview index.html                  (render it in the 👀 preview card; omit the name = the last file)`,

    subs: {

      list: function (a) {
        var all = Object.keys(window.SANDBOX || {}).sort()
        var dir = (flag(a, 'dir') || a._.join(' ')).trim()
        if (dir) all = all.filter(function (n) { return n.indexOf(dir) === 0 })
        return all.length ? 'sandbox' + (dir ? ' /' + dir : '') + ' (' + all.length + '):\n' + all.map(function (n) { return '· ' + n }).join('\n') : 'ozfile list: nothing here' + (dir ? ' under "' + dir + '"' : '') + '.'
      },

      read: function (a) {
        var name = a._[0]
        var f = sb(name)
        if (!f || typeof f.data !== 'string') return 'ozfile read: "' + name + '" isn\'t in the sandbox — `ozfile new` or `write` to create it.'
        reveal(name)
        var lines = f.data.split('\n'), CAP = 500
        var body = lines.slice(0, CAP).map(function (l, i) { return (i + 1) + '\t' + l }).join('\n')
        var tail = lines.length > CAP ? '\n…(' + (lines.length - CAP) + ' more lines — ask for a part)' : ''
        return 'read ' + name + ' — ' + lines.length + ' lines (numbered):\n' + body + tail
      },

      new: function (a) {
        var name = a._[0]
        if (!name) return 'ozfile new: give it a short plain name like "page.html".'
        if (sb(name)) return 'ozfile new: "' + name + '" already exists — `ozfile read` to open it, `add`/`write` to change it. won\'t clobber.'
        var ext = extOf(name)
        var skel = ext === 'html' ? '<!DOCTYPE html>\n<html>\n<head>\n  <meta charset="utf-8">\n  <title></title>\n</head>\n<body>\n\n</body>\n</html>\n'
          : ext === 'css' ? '/* ' + name + ' */\n\n'
          : ext === 'js' ? '// ' + name + '\n\n'
          : ''
        fileWrite(name, skel, flag(a, 'kind') || 'code')
        return 'ozfile new — ' + name + ' created' + (skel ? ' with a starter' : ' (blank)') + '. fill it with `write` or `add`.'
      },

      write: function (a) {
        var name = a._[0]
        if (!name) return 'ozfile write: pass a name + the content (quoted).'
        var content = a._.length > 1 ? rest(a) : flag(a, 'content')
        var existed = !!sb(name)
        fileWrite(name, content, flag(a, 'kind') || 'code')
        return 'ozfile write — ' + name + ' · ' + String(content).split('\n').length + ' lines ' + (existed ? '(overwrote)' : '(new)') + '.'
      },

      add: function (a) {
        var name = a._[0]
        var f = sb(name)
        if (!f || typeof f.data !== 'string') return 'ozfile add: "' + name + '" isn\'t in the sandbox — `ozfile new` or `write` first.'
        var content = rest(a)
        if (!content) return 'ozfile add: pass the lines to insert (quoted).'
        var lines = f.data.split('\n'), block = content.split('\n'), w = flag(a, 'where') || 'end'
        var at, label
        if (w === 'beginning' || w === 'top' || w === 'start') { at = 0; label = 'at the top' }
        else if (w === 'end' || w === 'bottom') { at = lines.length; label = 'at the end' }
        else { var n = parseInt(w, 10); if (isNaN(n) || n >= lines.length) { at = lines.length; label = 'at the end' } else { at = Math.max(0, n); label = 'after line ' + at } }
        lines.splice.apply(lines, [at, 0].concat(block))
        fileWrite(name, lines.join('\n'), f.kind)
        return 'ozfile add — ' + block.length + ' line(s) inserted ' + label + '. ' + name + ' is now ' + lines.length + ' lines.'
      },

      edit: function (a) {
        var name = a._[0]
        var f = sb(name)
        if (!f || typeof f.data !== 'string') return 'ozfile edit: "' + name + '" isn\'t in the sandbox — `write` first.'
        var oldT = flag(a, 'old')
        if (!oldT) return 'ozfile edit: pass --old "the exact text" (and --new).'
        var newT = flag(a, 'new')   // '' = delete
        var lines = f.data.split('\n')
        var from = Math.max(1, parseInt(flag(a, 'from'), 10) || 1)
        var to = Math.min(lines.length, parseInt(flag(a, 'to'), 10) || lines.length)
        var head = lines.slice(0, from - 1), body = lines.slice(from - 1, to).join('\n'), tail = lines.slice(to)
        var i = body.indexOf(oldT)
        if (i < 0) return 'ozfile edit: --old isn\'t in lines ' + from + '–' + to + ' of ' + name + ' — re-read + copy it exactly (widen --from/--to).'
        if (body.indexOf(oldT, i + oldT.length) >= 0) return 'ozfile edit: --old appears 2+× in lines ' + from + '–' + to + ' — pin it with --from/--to.'
        var newBody = body.slice(0, i) + newT + body.slice(i + oldT.length)
        var data = head.concat(newBody.split('\n'), tail).join('\n')
        fileWrite(name, data, f.kind)
        return 'ozfile edit — swapped ' + oldT.split('\n').length + ' line(s) for ' + String(newT).split('\n').length + ' in ' + name + '. now ' + data.split('\n').length + ' lines.'
      },

      template: function (a) {
        var key = a._[0] || flag(a, 'key')
        var list = window.MONACO_TEMPLATES || []
        var t = list.find(function (x) { return x.ai !== false && (x.key === key || x.filename === key) })
        if (!t) return 'ozfile template: no template "' + key + '" — available: ' + (list.filter(function (x) { return x.ai !== false }).map(function (x) { return x.key }).join(', ') || '(none)') + '.'
        if (t.path) { fileWrite(t.filename, t.path, 'path'); previewFile(t.filename); return 'ozfile template — opened ' + t.filename + ' (' + (t.label || t.key) + '), a folder template. previewing now.' }
        fileWrite(t.filename, t.data, t.kind || 'code')
        return 'ozfile template — opened ' + t.filename + ' (' + (t.label || t.key) + ') — ' + String(t.data).split('\n').length + ' lines. `ozfile preview` to run it.'
      },

      preview: function (a) {
        var name = a._[0]
        if (!name || !sb(name)) { if (lastWrite && sb(lastWrite)) name = lastWrite }
        if (!name) return 'ozfile preview: nothing to preview yet — `write` a file first.'
        if (!sb(name)) return 'ozfile preview: "' + name + '" isn\'t in the sandbox — `write` first.'
        return previewFile(name) ? 'ozfile preview — rendering ' + name + '.' : 'ozfile preview: couldn\'t open the preview card.'
      }

    }
  })

})()
