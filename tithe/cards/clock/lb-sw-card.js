//   running time FILLS the width — it shrinks if the card shrinks or you add units, so no space
//   is ever wasted. Buttons sit right under it. Laps live in a fixed box with 4 ruled slots, so
//   the card never resizes and nothing shifts while you run.
// FOR AI:
//   1. ONE source of truth with the bar: localStorage clock-stopwatch
//      { running, since, banked, laps[] } — elapsed = banked + (running ? Date.now()-since : 0).
//      Wall-clock, never a tick accumulator, so nothing drifts or freezes when throttled.
//   2. ⚠️ THE DROPPED-CLICK RULE: this renders 25×/sec. NEVER write to the DOM unless the value
//      changed — assigning .textContent replaces the text node and swallows clicks mid-press.
//      Every write goes through set(). (Sum hit this twice; see the memory note.)
//   3. Type is SIZED IN JS to fill the width (CSS can't fit-text-to-box). Recomputed only when
//      the width or the character count changes.
//   4. LAPS OFF (clock-sw-laps = false) → no lap button, no stats, no list. Just a big stopwatch.

