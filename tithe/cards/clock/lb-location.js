;(function () {

  const KEY       = 'clock-location'
  const PREFS_KEY = 'clock-location-prefs'

  // ── read / write ──────────────────────────────────────────

  function get() {
    try { return JSON.parse(localStorage.getItem(KEY)) || null } catch { return null }
  }

  function set(loc) {
    localStorage.setItem(KEY, JSON.stringify({ ...loc, ts: Date.now() }))
  }

  function getPrefs() {
    const defaults = { detect: false, weather: false, sunmoon: true, tz: false }
    try { return { ...defaults, ...JSON.parse(localStorage.getItem(PREFS_KEY)) } }
    catch { return defaults }
  }

  function setPrefs(prefs) {
    localStorage.setItem(PREFS_KEY, JSON.stringify(prefs))
  }

  // ── haversine — km between two lat/lon points ─────────────
  // the sphere math every navigation app uses.
  // input: degrees. output: kilometers.

  function km(lat1, lon1, lat2, lon2) {
    const R    = 6371
    const dLat = (lat2 - lat1) * Math.PI / 180
    const dLon = (lon2 - lon1) * Math.PI / 180
    const a    = Math.sin(dLat / 2) ** 2
               + Math.cos(lat1 * Math.PI / 180)
               * Math.cos(lat2 * Math.PI / 180)
               * Math.sin(dLon / 2) ** 2
    return R * 2 * Math.asin(Math.sqrt(a))
  }

  // ── detect — one-shot GPS request ────────────────────────
  // Promise resolves with { lat, lon, tz, accuracy, source, ts }.
  // saves to localStorage on success.
  // timeout: 8s. maximumAge: 60s cached reading is fine.

  function detect() {
    return new Promise((resolve, reject) => {
      if (!navigator.geolocation) {
        reject(new Error('geolocation not supported'))
        return
      }
      navigator.geolocation.getCurrentPosition(
        pos => {
          const { latitude: lat, longitude: lon, accuracy } = pos.coords
          const tz  = Intl.DateTimeFormat().resolvedOptions().timeZone
          const loc = { lat, lon, tz, accuracy, source: 'gps', ts: Date.now() }
          set(loc)
          resolve(loc)
        },
        err  => reject(err),
        { timeout: 8000, maximumAge: 60000 }
      )
    })
  }

  // ── watch — continuous position monitor ──────────────────
  // fires onChange({ loc, kmMoved, tzChanged }) only when the
  // device has moved > thresholdKm OR the timezone string changed.
  // returns watchId — pass to navigator.geolocation.clearWatch() to stop.

  function watch({ thresholdKm = 50, onChange } = {}) {
    if (!navigator.geolocation || typeof onChange !== 'function') return null

    const stored = get()

    const id = navigator.geolocation.watchPosition(pos => {
      const { latitude: lat, longitude: lon } = pos.coords
      const tz       = Intl.DateTimeFormat().resolvedOptions().timeZone
      const loc      = { lat, lon, tz, source: 'gps', ts: Date.now() }
      const kmMoved  = stored ? km(stored.lat, stored.lon, lat, lon) : 0
      const tzChanged = stored ? tz !== stored.tz : false

      if (kmMoved > thresholdKm || tzChanged) onChange({ loc, kmMoved, tzChanged })
    },
    () => {},   // silent error — GPS loss is normal on laptops
    { enableHighAccuracy: false, maximumAge: 300000 })

    return id
  }

  // ── reverseGeocode — Nominatim lat/lon → "City, State" ───
  // free, no key. returns a Promise<string>.
  // rate limit: 1 req/s. call only on manual detect, not in watch loop.

  async function reverseGeocode(lat, lon) {
    const url = `https://nominatim.openstreetmap.org/reverse`
              + `?lat=${lat}&lon=${lon}&format=json`
    const r   = await fetch(url, { headers: { 'Accept-Language': 'en' } })
    const d   = await r.json()
    const a   = d.address || {}
    const city  = a.city || a.town || a.village || a.county || ''
    const state = a.state || ''
    return [city, state].filter(Boolean).join(', ')
  }

  // ── export ────────────────────────────────────────────────

  window.LBLocation = { get, set, getPrefs, setPrefs, km, detect, watch, reverseGeocode }

})()
