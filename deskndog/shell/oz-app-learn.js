;(function () {
  'use strict'

  var APP = window.OZ_APP_CLI; if (!APP) return
  var flag = APP.flag

  // ── learn* — the profile's data helpers. same localStorage keys the beans wrote ──

  function getLS(k, d) {
    try { var v = localStorage.getItem(k); return v == null ? d : v } catch (_) { return d }
  }

  function setLS(k, v) {
    try { localStorage.setItem(k, String(v)) } catch (_) {}   // the open card re-reads on gear-open
  }

  function disorders() {   // toto_learn_disorders — an array of accommodation names
    try { return JSON.parse(getLS('toto_learn_disorders', '[]')) || [] } catch (_) { return [] }
  }

  function disSet(a) { setLS('toto_learn_disorders', JSON.stringify(a)) }

  // ── learnRead — render the profile back the way read_learn_profile did (how/style/level/hard + dis) ──

  function learnRead() {
    var g = function (k) { return getLS(k, '') }, dis = disorders()
    return 'learner profile:\n' +
      '· how: '            + (g('toto_learn_how')   || '—') + '\n' +
      '· style: '          + (g('toto_learn_style') || '—') + '\n' +
      '· level: '          + (g('toto_learn_level') || '—') + '\n' +
      '· hard: '           + (g('toto_learn_hard')  || '—') + '\n' +
      '· accommodations: ' + (dis.length ? dis.join(', ') : '—')
  }

  // ── field — the four setters share a shape: one positional value → one key (overwrites) ──

  function field(sub, key, label) {
    return function (a) {
      var v = a._.join(' ').trim()
      if (!v) return 'ozlearn ' + sub + ': pass the ' + label + ' (in quotes).'
      setLS(key, v)
      return 'ozlearn ' + sub + ' — ' + label + ' = "' + v + '".'
    }
  }

  // ── the seven subcommands — each is one old bean. positionals for the value, --name for a disorder ──

  APP.makeApp({
    name: 'ozlearn',
    blurb: 'the learner profile — how / style / level / hard + accommodations the tutor pitches lessons from',
    clue:
`ozlearn — the learner profile, as a CLI. the tutor reads it to pitch lessons at the
learner's level. run \`ozlearn read\` first to see what's there; edit one field at a time.
  ozlearn read
  ozlearn set-how "examples first, then the rule"
  ozlearn set-style "visual"
  ozlearn set-level "undergrad"
  ozlearn set-hard "abstract notation; needs it grounded"
  ozlearn add-disorder --name ADHD
  ozlearn remove-disorder --name ADHD
--name takes an accommodation to hold (add) or drop (remove); the rest is the field's value in quotes.`,

    subs: {

      read: function () { return learnRead() },

      'set-how':   field('set-how',   'toto_learn_how',   'how they want to learn'),
      'set-style': field('set-style', 'toto_learn_style', 'learning style'),
      'set-level': field('set-level', 'toto_learn_level', 'level'),
      'set-hard':  field('set-hard',  'toto_learn_hard',  'what they find hard'),

      'add-disorder': function (a) {
        var n = (flag(a, 'name') || a._.join(' ')).trim()
        if (!n) return 'ozlearn add-disorder: pass a --name.'
        var arr = disorders()
        if (arr.indexOf(n) < 0) arr.push(n)
        disSet(arr)
        return 'ozlearn add-disorder — "' + n + '" noted (' + arr.length + ' total).'
      },

      'remove-disorder': function (a) {
        var n = (flag(a, 'name') || a._.join(' ')).trim()
        if (!n) return 'ozlearn remove-disorder: pass a --name.'
        var arr = disorders(), next = arr.filter(function (x) { return x !== n })
        if (next.length === arr.length) return 'ozlearn remove-disorder: "' + n + '" not in the list.'
        disSet(next)
        return 'ozlearn remove-disorder — removed "' + n + '".'
      }

    }
  })

})()
