;(function () {
  'use strict'

  var APP = window.OZ_APP_CLI; if (!APP) return
  var flag = APP.flag

  // ── chart* — the notes store helpers. load (null = malformed), save (+ recompile every head) ──

  function notesLoad() {
    try { var n = JSON.parse(localStorage.getItem('toto_notes') || '[]'); return Array.isArray(n) ? n : [] }
    catch (_) { return null }
  }

  function notesSave(n) {
    try { localStorage.setItem('toto_notes', JSON.stringify(n)) } catch (_) {}
    if (window.cacheAllCharts) window.cacheAllCharts()   // every agent's warm head recompiles
  }

  function noteUid() { return 'note-' + Date.now().toString(36) + Math.floor(Math.random() * 999).toString(36) }

  // ── chartRead — the compiled head for an agent (mirror of read_chart), capped so it fits ──

  function chartRead(id) {
    id = id || 'toto'
    var head = null
    try { head = localStorage.getItem('toto_chart_' + id) } catch (_) {}
    if (!head && window.compileChart) { try { head = window.compileChart(id) } catch (_) {} }
    if (!head) return 'ozchart: no chart for "' + id + '" yet — open the injection config first.'
    var lines = head.split('\n'), CAP = 400
    return 'chart for ' + id + ' (' + lines.length + ' lines):\n' + lines.slice(0, CAP).join('\n') +
      (lines.length > CAP ? '\n…(' + (lines.length - CAP) + ' more — ask for a part)' : '')
  }

  // ── the subcommands — read the head · tend the notes (add/edit/toggle) · set the patient bio ──

  APP.makeApp({
    name: 'ozchart',
    blurb: 'the patient chart — read the head, tend the notes, set the bio (recompiles every head)',
    clue:
`ozchart — the patient's injection chart, as a CLI. the chart IS the patient's memory. read
before you write. notes are the nurse's private chart unless you share them (--owner hil).
  ozchart read --agent toto
  ozchart notes-add --display "Penicillin allergy" --body "flagged 2026-06 — no beta-lactams"
  ozchart notes-add --display "Loves cats" --owner hil          (shared with everyone; --off = dormant)
  ozchart notes-edit --name note-123 --body "updated text"
  ozchart notes-toggle --name note-123 --off                    (--on · --off · or neither = flip)
  ozchart bio --name Sam --pronouns they/them --label "Patient 00-000-001" --who "yoga teacher, builder"`,

    subs: {

      read: function (a) { return chartRead(flag(a, 'agent') || a._[0]) },

      'notes-add': function (a) {
        var n = notesLoad(); if (!n) return 'ozchart notes-add: the notes store is malformed JSON.'
        var display = flag(a, 'display') || a._.join(' ').trim()
        if (!display) return 'ozchart notes-add: pass --display (the note title).'
        var nm = noteUid()
        n.push({ folder: flag(a, 'folder') || null, name: nm, display: display, on: !a.flags.off, body: flag(a, 'body'), owner: flag(a, 'owner') || 'nurse' })
        notesSave(n)
        return 'ozchart notes-add — added "' + display + '" (' + nm + '). every head recompiled.'
      },

      'notes-edit': function (a) {
        var n = notesLoad(); if (!n) return 'ozchart notes-edit: the notes store is malformed JSON.'
        var note = n.find(function (x) { return x.name === flag(a, 'name') })
        if (!note) return 'ozchart notes-edit: no note "' + flag(a, 'name') + '".'
        if (flag(a, 'body')) note.body = flag(a, 'body')
        if (flag(a, 'display')) note.display = flag(a, 'display')
        notesSave(n)
        return 'ozchart notes-edit — edited ' + flag(a, 'name') + '. every head recompiled.'
      },

      'notes-toggle': function (a) {
        var n = notesLoad(); if (!n) return 'ozchart notes-toggle: the notes store is malformed JSON.'
        var note = n.find(function (x) { return x.name === flag(a, 'name') })
        if (!note) return 'ozchart notes-toggle: no note "' + flag(a, 'name') + '".'
        note.on = a.flags.on ? true : a.flags.off ? false : !note.on
        notesSave(n)
        return 'ozchart notes-toggle — ' + flag(a, 'name') + ' → ' + (note.on ? 'on' : 'off') + '. every head recompiled.'
      },

      bio: function (a) {
        var map = { name: 'toto_userName', pronouns: 'toto_userPronouns', label: 'toto_userPatientLabel', who: 'toto_userWho' }, set = []
        Object.keys(map).forEach(function (k) {
          if (flag(a, k)) { try { localStorage.setItem(map[k], flag(a, k)); set.push(k + '="' + flag(a, k) + '"') } catch (_) {} }
        })
        if (!set.length) return 'ozchart bio: pass --name / --pronouns / --label.'
        if (window.cacheAllCharts) window.cacheAllCharts()
        return 'ozchart bio — set ' + set.join(' · ') + '. every head recompiled.'
      }

    }
  })

})()
