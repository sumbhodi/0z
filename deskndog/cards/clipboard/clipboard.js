  if (!guides.length) return `${note}<div class="clip-subbar">${addChip}</div><div class="clip-cfile-empty">no quick guides yet — add one</div>`
  const idx = Math.min(ui.guide || 0, guides.length - 1)
  const sub = guides.map((g, i) =>
    `<button class="clip-chip clip-gsub${i === idx ? ' on' : ''}" data-guide="${i}" title="${prepEsc(g.title || 'untitled')}">${prepEsc(g.title || 'untitled')}</button>`).join('') + addChip
