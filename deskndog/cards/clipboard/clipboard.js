function prepEsc(s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;') }

// the blank template — one empty row per section, so a fresh sheet shows its skeleton. placeholders (below)
// carry the guidance; the values stay empty until you fill them. nurse + HIL share this one doc.
// a stable id for a complaint file (cross-filing needs identity, not array position)
function cmpId() { return 'c' + Date.now().toString(36) + Math.random().toString(36).slice(2, 5) }

function prepFresh() {
  return {
    // ── OVERVIEW — three WHOLE-FILE docs (not boxes), switched by a sub-bar ──
    patient: '', presentation: '', perspective: '', comorbidity: '',
    // ── COMPLAINTS — folders (body systems + environmental) holding files; cross-filed; NEVER a diagnosis ──
    complaints: [],
    // ── QUICK GUIDES — survival cheat-sheets (one protocol per card) ──
    guides: [],
    // ── PREP (the session sheet — the page the patient prints + brings) ──
    discipline: '', date: '', seeing: '',
    sayFirst: '',
    scope:    [{ item: '', time: '' }],
    topics:   [{ heading: '', bullets: [''], flags: [''] }],
    snapshot: [{ domain: '', rating: '', evidence: '' }],
    qa:       [{ q: '', a: '' }],
    bring:    [''],
  }
}
// is a doc's BODY blank? (discipline/date/seeing are just a label — a real prep needs a say-first or a section)
// → treat label-only docs like unsaved, so the worked sample shows instead of an empty shell.
function prepIsEmpty(d) {
  if (!d) return true
  if ((d.patient || '').trim() || (d.presentation || '').trim() || (d.perspective || '').trim() || (d.comorbidity || '').trim()) return false
  if ((d.complaints || []).some(c => (c.title || '').trim() || (c.body || '').trim())) return false
  if ((d.guides || []).some(g => (g.title || '').trim() || (g.body || '').trim())) return false
  if ((d.sayFirst || '').trim()) return false
  if ((d.scope || []).some(r => (r.item || '').trim() || (r.time || '').trim())) return false
  if ((d.topics || []).some(t => (t.heading || '').trim() || (t.bullets || []).some(b => (b || '').trim()) || (t.flags || []).some(f => (f || '').trim()))) return false
  if ((d.snapshot || []).some(r => (r.domain || '').trim() || (r.rating || '').trim() || (r.evidence || '').trim())) return false
  if ((d.qa || []).some(r => (r.q || '').trim() || (r.a || '').trim())) return false
  if ((d.bring || []).some(b => (b || '').trim())) return false
  return true
}
// migrate a pre-folders doc (old: presents + complaints[{complaint,specialist}]) → current shape, so stale
// localStorage and saved sessions don't render orphaned. best-effort routes the old free-text specialist to a folder.
function specToFolder(s) {
  s = (s || '').toLowerCase()
  if (/cardio|heart|\bbp\b|blood pressure/.test(s)) return 'cardio'
  if (/neuro|migraine|head|nerve|seizure/.test(s)) return 'neuro'
  if (/ortho|muscul|skelet|\bpt\b|physical|back|joint|edema/.test(s)) return 'msk'
  if (/psych|therap|lcsw|mood|mental|sleep/.test(s)) return 'psych'
  return 'env'
}
function prepMigrate(d) {
  if (d.presents && !d.presentation) d.presentation = d.presents
  delete d.presents
  if (Array.isArray(d.complaints)) d.complaints = d.complaints.map(c =>
    c && 'complaint' in c ? { id: cmpId(), title: c.complaint || '', body: '', folders: [specToFolder(c.specialist)] } : c)
  return d
}
// the chart has two SIDES: 'ai' (the nurse's notes — seeds the worked demo) and 'hil' (the human's own — ships BLANK).
// each persists to its own key; the nurse's beans + watcher use the AI side (toto_prep), the human fills the HIL side.
function prepKey(side) { return side === 'hil' ? 'toto_prep_hil' : 'toto_prep' }
function prepGet(side) {
  side = side || 'ai'
  let saved = null
  try { saved = JSON.parse(localStorage.getItem(prepKey(side)) || 'null') } catch (_) {}
  if (saved && typeof saved === 'object') { saved = prepMigrate(Object.assign(prepFresh(), saved)); if (!prepIsEmpty(saved)) return saved }
  // AI side blank/unsaved → seed the worked mockup (the nurse's notes — the toto demo). HIL side stays blank: the
  // human fills it themselves. type anything on either side and it's yours.
  if (side !== 'hil' && window.DEMO_PREP) { try { return Object.assign(prepFresh(), JSON.parse(JSON.stringify(window.DEMO_PREP))) } catch (_) {} }
  return prepFresh()
}
function prepSet(doc) {
  try { localStorage.setItem('toto_prep', JSON.stringify(doc)) } catch (_) {}
  window.dispatchEvent(new CustomEvent('toto-prep-changed'))   // an open card (or the watcher) re-reads
}
// set a dotted path (scope.2.item, topics.0.bullets.1) into the doc
function prepPath(o, path, val) {
  const ks = path.split('.'); let t = o
  for (let i = 0; i < ks.length - 1; i++) { const k = ks[i]; t = t[/^\d+$/.test(k) ? +k : k] }
  t[ks[ks.length - 1]] = val
}

