// the readable text the nurse's note carries (the chart injects text, not JSON)
function prepToText(doc) {
  const L = []
  L.push(`${doc.patient || doc.discipline || 'session'} — chart${doc.date ? ' · ' + doc.date : ''}${doc.seeing ? ' · ' + doc.seeing : ''}`)
  if ((doc.presentation || '').trim()) L.push(`presentation: ${doc.presentation}`)
  if ((doc.perspective || '').trim()) L.push(`perspective: ${doc.perspective}`)
  if ((doc.comorbidity || '').trim()) L.push(`co-morbidity: ${doc.comorbidity}`)
  ;(doc.complaints || []).filter(c => (c.title || '').trim() || (c.body || '').trim()).forEach(c => L.push(`complaint [${(c.folders || []).join(', ')}]: ${c.title}${c.body ? ' — ' + c.body : ''}`))
  ;(doc.guides || []).filter(g => (g.title || '').trim() || (g.body || '').trim()).forEach(g => L.push(`quick guide: ${g.title}${g.body ? '\n' + g.body : ''}`))
  if ((doc.sayFirst || '').trim()) L.push(`say first: ${doc.sayFirst}`)
  ;(doc.scope || []).filter(r => r.item || r.time).forEach(r => L.push(`• ${r.item}${r.time ? ' (' + r.time + ')' : ''}`))
  ;(doc.topics || []).forEach(t => { if (t.heading || (t.bullets || []).some(Boolean)) { L.push(`# ${t.heading || ''}`); (t.bullets || []).filter(Boolean).forEach(b => L.push(`  - ${b}`)); (t.flags || []).filter(Boolean).forEach(f => L.push(`  ⚠ ${f}`)) } })
  ;(doc.snapshot || []).filter(r => r.domain).forEach(r => L.push(`${r.domain}: ${r.rating || ''} — ${r.evidence || ''}`))
  ;(doc.qa || []).filter(r => r.q).forEach(r => L.push(`Q: ${r.q}\nA: ${r.a || ''}`))
  ;(doc.bring || []).filter(Boolean).forEach(b => L.push(`bring: ${b}`))
  return L.join('\n')
}
// mirror a session into / out of the nurse's chart notes (toto_notes)
function nurseNoteAdd(id, label, body) {
  let n = []; try { n = JSON.parse(localStorage.getItem('toto_notes') || '[]') } catch (_) {}
  n.push({ folder: 'session-prep', name: 'prep-' + id, display: label, on: false, body, owner: 'nurse' })
  try { localStorage.setItem('toto_notes', JSON.stringify(n)) } catch (_) {}
}
function nurseNoteRemove(id) {
  let n = []; try { n = JSON.parse(localStorage.getItem('toto_notes') || '[]') } catch (_) {}
  try { localStorage.setItem('toto_notes', JSON.stringify(n.filter(x => x.name !== 'prep-' + id))) } catch (_) {}
}
// exposed so the nurse's prep_save bean reuses the EXACT save (a session + a nurse note) the 💾 button uses
window.prepSaveSession = function (doc) {
  const id = sessId(), label = sessLabel(doc), list = loadSessions()
  list.push({ id, discipline: doc.discipline || '', label, savedAt: Date.now(), doc: JSON.parse(JSON.stringify(doc)) })
  saveSessions(list); nurseNoteAdd(id, label, prepToText(doc))
  return label
}

