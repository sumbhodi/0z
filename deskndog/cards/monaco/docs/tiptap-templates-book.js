<p>The executive function of the brain is the ability to inhibit stimuli. The ability to choose to focus on something is the only thing we really have any control over. I can’t control the weather or the stock market or I would be a billionaire living in a subtropical rainforest.  Just one billion, I’m not greedy.</p>

