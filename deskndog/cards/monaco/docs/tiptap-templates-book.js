<p>Safely seated on my cushion or within the confines of my yoga mat and practice I have no need to safely navigate space. My eyes, a darwinian marvel, are superfluous. I don’t remember if I am stardust or mostly a sack of recycled dinosaur piss. I simply don’t care.</p>

