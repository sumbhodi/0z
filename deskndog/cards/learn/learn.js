  function shelve(L) {
    if (!L || !L.topic || !L.core) return
    const list = lcLoad()
    const key = String(L.topic).trim().toLowerCase()
    // ⭐ A LESSON INSIDE A CLASS FILES BACK INTO ITS CLASS (2026-08-28). shelve predates the class
    //   shelf: it keys one course PER TOPIC, so a lesson dived out of "CSIS-1430 web" and then
    //   worked (a practice bought, a test sat) would come back as a brand-new standalone row named
    //   after the lesson — the class silently stops accumulating. So: any class already holding a
    //   lesson with this topic gets the update IN PLACE, pools and all; only an unclaimed topic
    //   falls through to the old one-topic-one-course road below (still right for ad-hoc lessons).
    for (let ci = 0; ci < list.length; ci++) {
      const li = (list[ci].lessons || []).findIndex(x => String(x.topic || '').trim().toLowerCase() === key)
      if (li > -1 && ((list[ci].lessons || []).length > 1 || String(list[ci].title || '').trim().toLowerCase() !== key)) {
        const kept = list[ci].lessons[li]
        list[ci].lessons[li] = Object.assign({}, kept, JSON.parse(JSON.stringify(L)), { module: L.module || kept.module || null })
        lcSave(list)
        try { const el = card.querySelector('.lc-list'); if (el) el.innerHTML = lcRows() } catch (_) {}
        return
      }
    }
    // ⭐⭐ A NEW LESSON THAT NAMES ITS CLASS FILES INTO IT (1 Sep 2026, Sum: "something isn't saving them
    //    into class right"). The loop above only rescues a lesson the class ALREADY holds — so a brand
    //    new one could never join a class at all. Chicken and egg: to be filed under CS-1410 it first
    //    had to be filed under CS-1410. Every fresh lesson therefore fell through to the standalone road
    //    below and became its own course row named after its topic, which is why the class kept reading
    //    "no lessons yet" while lessons piled up beside it.
    //    ⚠ The class must ALREADY BE ON THE SHELF — this files into an existing row, it never invents a
    //    class from a typo. An unknown course name falls through to the standalone road, same as before.
    const cname = String(L.course || L.subject || '').trim().toLowerCase()
    if (cname) {
      const ci = list.findIndex(c => String(c.title || '').trim().toLowerCase() === cname)
      if (ci > -1) {
        const ls = list[ci].lessons || (list[ci].lessons = [])
        const li = ls.findIndex(x => String(x.topic || '').trim().toLowerCase() === key)
        const fresh = JSON.parse(JSON.stringify(L))
        if (li > -1) ls[li] = Object.assign({}, ls[li], fresh)   // same topic twice = an edit, not a second copy
        else ls.push(fresh)
        lcSave(list)
        try { const el = card.querySelector('.lc-list'); if (el) el.innerHTML = lcRows() } catch (_) {}
        return
      }
    }
    const at = list.findIndex(c => String(c.title || '').trim().toLowerCase() === key)
    // the category is decided ONCE, on first file, and never re-guessed — a shelf that silently
    // re-sorts itself as a lesson grows is a shelf you cannot find anything on. A category already
    // set (by a previous guess, the tutor, or a human) always wins.
    const had = at > -1 ? list[at].cat : null
    const row = { id: at > -1 ? list[at].id : lcId(), title: L.topic, savedAt: Date.now(),
                  cat: had || L.cat || guessCat(L.topic, L.core) || null,
                  subject: L.subject || null, level: L.level || null, module: L.module || null,
                  lessons: [JSON.parse(JSON.stringify(L))] }
    if (at > -1) list[at] = row; else list.unshift(row)
    lcSave(list)
    // ⚠ I called renderCourses() here and it does not exist — the shelf filled and the bar never
    //   repainted, so it read "no saved courses yet" while holding lessons. lcRows() is the renderer.
    try { const el = card.querySelector('.lc-list'); if (el) el.innerHTML = lcRows() } catch (_) {}
    // the word list drew a blank → ask the model ONCE, in the background. Never blocks the shelf.
    if (!row.cat) { try { catAsk(row.title) } catch (_) {} }
  }

