  // ── THE PREAMBLE STRIPPER — GOFAI (Sum 2026-08-17: "it admitted it needed to search first then
  //   answered anyway?"). A model told "no preamble" will still open with "I need to search for
  //   current physics information on black holes to build this section properly." — it is narrating
