// score every category and take the best — a topic like "the physics of music" hits two lists, and
// picking the FIRST match would make the answer depend on key order rather than on the topic.
function guessCat(title, body) {
  const hay = (String(title || '') + ' ' + String(body || '').replace(/<[^>]+>/g, ' ')).toLowerCase()
  if (!hay.trim()) return ''
  let best = '', top = 0
  Object.keys(CATS).forEach(k => {
    let score = 0
    CATS[k].forEach(w => {
      // ⚠ WORD-BOUNDARY, NOT SUBSTRING. Plain indexOf filed "the Schwarzschild radius" under
      //   HISTORY, because 'war' is inside Sch-WAR-zschild. Terms are PREFIXES by default so
      //   'histor' catches history/historical — but a bare \\b at the front is not enough either:
      //   'war' still prefix-matched "WARp of spacetime". A trailing $ marks a WHOLE-WORD term
      //   (plural allowed), which is what the short collision-prone words need.
      const whole = w.endsWith('$')
      const t = (whole ? w.slice(0, -1) : w).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
      const rx = new RegExp('\\b' + t + (whole ? 's?\\b' : ''))
      if (!rx.test(hay)) return
      // the TITLE is what the lesson is about; the body merely mentions things. Weight it.
      score += rx.test(String(title || '').toLowerCase()) ? 3 : 1
    })
    if (score > top) { top = score; best = k }
  })
  return top > 0 ? best : ''        // no match is an honest answer — '' means "ask someone else"
}

