// ── practice engine — endless. multi-step. wrong teaches; right advances. ──
function mountPractice(card) {
  const arena = card.querySelector('.lp-arena')
  const pool = SAMPLE.practice
  let pi = 0   // which problem (loops forever)

  function renderStep(si) {
    const prob = pool[pi]
    const s = prob.steps[si]
    const stepTag = prob.steps.length > 1 ? `<span class="lp-step">step ${si + 1} / ${prob.steps.length}</span>` : ''
    const choices = s.choices.map(c =>
      `<button class="lp-choice" data-ok="${c.ok}" data-why="${escapeAttr(c.why)}">${c.text}</button>`).join('')
    arena.innerHTML = `${stepTag}
      <p class="lp-prompt">${s.prompt}</p>
      <div class="lp-choices">${choices}</div>
      <div class="lp-feedback"></div>`

    const fb = arena.querySelector('.lp-feedback')
    const shownAt = Date.now(); let logged = false   // the stopwatch starts when the step renders
    arena.querySelectorAll('.lp-choice').forEach(c => c.addEventListener('click', () => {
      const ok = c.dataset.ok === 'true'
      if (!logged) {   // the FIRST answer to this step is the score — first-try correctness + time-to-answer
        logged = true; perfLog(prob.skill, ok, Date.now() - shownAt)
        const pg = card.querySelector('.lpg-list'); if (pg) pg.innerHTML = progressRows()
      }
      if (ok) {
        c.classList.add('lp-right')
        arena.querySelectorAll('.lp-choice').forEach(x => { x.disabled = true })
        fb.innerHTML = `<span class="lp-ok">✅ ${c.dataset.why}</span>`
        const next = si + 1
        setTimeout(() => (next < prob.steps.length ? renderStep(next) : renderDone()), 650)
      } else {
        c.classList.add('lp-wrong'); c.disabled = true
        fb.innerHTML = `<span class="lp-no">${c.dataset.why}</span>`
      }
    }))
  }

  // problem finished → the fork: keep exploring (next, forever) or take the test
  function renderDone() {
    arena.innerHTML = `
      <p class="lp-done">nice. that one's yours.</p>
      <div class="lp-donerow">
        <button class="lp-go">keep exploring →</button>
        <button class="lp-totest">take the test ✅</button>
      </div>`
    arena.querySelector('.lp-go').addEventListener('click', () => { pi = (pi + 1) % pool.length; renderStep(0) })
    arena.querySelector('.lp-totest').addEventListener('click', () => {
      const test = card.querySelector('.lbar-test')
      if (test) { test.classList.add('open'); test.scrollIntoView({ behavior: 'smooth', block: 'start' }) }
    })
  }

  renderStep(0)
}

