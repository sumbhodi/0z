// ── performance tracker — THE APP COUNTS (deterministic, free, exact); the AI JUDGES (a bean reads this rollup
//    + writes the skills/weaknesses list, moving weak→skill on a trend). every answer logs { skill, ok, ms }. ──
function perfLoad() { try { const a = JSON.parse(localStorage.getItem('toto_learn_perf') || '[]'); return Array.isArray(a) ? a : [] } catch (_) { return [] } }
function perfLog(skill, ok, ms) { const a = perfLoad(); a.push({ skill: skill || 'general', ok: !!ok, ms: ms | 0, at: Date.now() }); try { localStorage.setItem('toto_learn_perf', JSON.stringify(a.slice(-500))) } catch (_) {} }
function perfRollup() {
  const by = {}; perfLoad().forEach(r => { (by[r.skill] = by[r.skill] || []).push(r) })
  return Object.keys(by).map(skill => {
    const rows = by[skill], n = rows.length, right = rows.filter(r => r.ok).length
    const ms = rows.filter(r => r.ms > 0).map(r => r.ms), avgMs = ms.length ? Math.round(ms.reduce((a, b) => a + b, 0) / ms.length) : 0
    const half = Math.max(1, Math.floor(n / 2))
    const earlyPct = Math.round(100 * rows.slice(0, half).filter(r => r.ok).length / half)
    const recentPct = Math.round(100 * rows.slice(-half).filter(r => r.ok).length / half)
    return { skill, n, pct: Math.round(100 * right / n), avgMs, earlyPct, recentPct }
  }).sort((a, b) => a.pct - b.pct)   // weakest first — the AI reads this list when it builds the next practice
}
// the DETERMINISTIC stand-in for the AI's judgment (live tutor replaces this; same rollup in, same shape out)
function perfTier(r) {
  if (r.n < 3) return { tier: 'new', label: 'warming up' }
  if (r.pct >= 80) return { tier: 'skill', label: r.recentPct - r.earlyPct >= 25 ? 'skill ↑ (was weak)' : 'skill' }
  if (r.pct < 55) return { tier: 'weak', label: 'weak spot' }
  return { tier: 'mid', label: 'practicing' }
}
function progressRows() {
  const rolls = perfRollup()
  if (!rolls.length) return `<div class="lpg-empty">answer some practice — your skills &amp; weak spots fill in from how you do (the AI writes them; here a simple rule stands in)</div>`
  return rolls.map(r => { const t = perfTier(r); return `<div class="lpg-row lpg-t-${t.tier}">
      <span class="lpg-skill">${escapeAttr(r.skill)}</span>
      <span class="lpg-bar"><span class="lpg-fill" style="width:${r.pct}%"></span></span>
      <span class="lpg-pct">${r.pct}%</span>
      <span class="lpg-time">${r.avgMs ? (r.avgMs / 1000).toFixed(1) + 's' : '—'}</span>
      <span class="lpg-tier">${t.label}</span>
    </div>` }).join('')
}

