  //   label (letters-and-digits compare, ≤4 chars of slack for "## " / ":" / "—"). A real opening
  //   sentence that happens to contain the words survives, because it is longer than the label.
  function stripEcho(text, label) {
    if (!label) return text
    const want = String(label).toLowerCase().replace(/[^a-z0-9]/g, '')
    if (!want) return text
    const m = String(text || '').match(/^\s*(?:<(h[1-6]|p|strong|b)>)?\s*([^\n<]{0,60}?)\s*(?:<\/\1>)?\s*(?:\n|<p|$)/)
    if (!m) return text
    const got = (m[2] || '').toLowerCase().replace(/[^a-z0-9]/g, '')
    if (!got || got !== want) return text          // not the label alone → it is content, leave it
    return String(text).slice(m[0].length).replace(/^\s+/, '')
  }

  function splitSources(text) {
    const links = []
    let body = stripPreamble(text)          // the think-out-loud opener goes before anything else
    let m; MD_LINK.lastIndex = 0
    while ((m = MD_LINK.exec(body))) links.push({ title: m[1], url: m[2] })
    const cut = body.search(SRC_HEAD)                       // a labelled sources block → all of it goes
    if (cut > -1) body = body.slice(0, cut)
    body = body.replace(MD_LINK, '$1')                      // link left inline → keep the words, drop the url
      .replace(/https?:\/\/[^\s<>"')\]]+/g, '')            // bare urls in the prose
      .replace(/[ \t]*[·•|]\s*(?=\n|$)/g, '')               // the separators they hang between them
      .replace(/\n{3,}/g, '\n\n').trim()
    return { body, links }
  }

