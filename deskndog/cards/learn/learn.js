  // ⭐ GOFAI CHECKS THE BOT — it does not replace it (Sum 2026-08-17: "have bot and gofai check each
  //   other's work… could be an edge case and gofai is wrong, could be hallucinate").
  //   The MODEL proposes the answer. The CARD recomputes it where the domain allows. What matters is
  //   that the two fail DIFFERENTLY: agreement is real evidence, disagreement is worth a flag.
  //   ⚠ IT MUST KNOW ITS OWN DOMAIN AND SAY NOTHING OUTSIDE IT. Arithmetic, yes. History, why the
  //     empire fell, what a poem means — no. A checker that answers outside its competence is just a
  //     confident wrong second opinion. SILENCE IS A VALID OUTPUT, and the common one.
  //   Returns { work, flag } — work is the arithmetic shown on the correct pick, flag is a
  //   disagreement worth surfacing. Both empty means "not my domain", which is fine.
  function gofaiCheck(q) {
    const right = (q.choices || []).find(c => c.ok)
    const nums = String(q.prompt || '').match(/-?\d[\d,]*\.?\d*/g) || []
    if (!right || nums.length < 2) return { work: '', flag: '' }          // not arithmetic → silent
    const a = parseFloat(nums[0].replace(/,/g, '')), b = parseFloat(nums[1].replace(/,/g, ''))
    const want = parseFloat(String(right.t).replace(/[^0-9.\-]/g, ''))
    if (!isFinite(a) || !isFinite(b) || !isFinite(want)) return { work: '', flag: '' }
    const ops = [['+', a + b], ['−', a - b], ['×', a * b], ['÷', b ? a / b : NaN]]
    const hit = ops.find(([, v]) => isFinite(v) && Math.abs(v - want) < 1e-9)
    if (hit) return { work: `${nums[0]} ${hit[0]} ${nums[1]} = ${right.t}`, flag: '' }   // they agree
    // no operation on the two numbers reaches the model's answer. Might be a multi-step question,
    // might be units, might be wrong. Flag it, do not overrule it — GOFAI is the one guessing here.
    return { work: '', flag: `⚠ the card could not reproduce ${right.t} from ${nums[0]} and ${nums[1]} — worth a look.` }
  }

