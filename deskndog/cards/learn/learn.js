  const META_OPEN = /^\s*(?:i(?:'|’)?(?:ll|m| will| need| should| am| have| can| want)|let me|first[,]?\s+i|to (?:answer|build|write|explain)|here(?:'|’)?s|here is|okay|ok|sure|alright|got it|understood)\b/i
  const META_VERB = /\b(search|look (?:it |this )?up|websearch|write|build|create|draft|section|snippet|answer|respond|explain|provide|start by|need more|current information)\b/i
  function stripPreamble(text) {
    let t = String(text || '')
    for (let pass = 0; pass < 3; pass++) {          // they sometimes stack two
      const m = t.match(/^\s*(?:<p>)?([^\n<]{0,300}?)(?:<\/p>)?\s*(?=\n|<p|$)/)
      if (!m) break
      const first = m[1] || ''
      if (first.length > 300) break
      if (!(META_OPEN.test(first) && META_VERB.test(first))) break
      t = t.slice(m[0].length)                      // that opener was about the work, not the topic
    }
    return t.replace(/^\s+/, '')
  }

