  //
  //   2 · THE EXTRACTOR WAS GREEDY. /[[{][\s\S]*[\]}]/ runs from the FIRST bracket to the LAST one
  //       in the whole reply — one stray brace in a preamble or a sign-off and the span is not JSON.
  //       Replaced with a fence strip and a BALANCED scan that stops on the brace that closes.
  //
  //   And it keeps the raw text on `askJSON.raw` so a failure can show what actually came back
  //   instead of only a verdict — the same proof-by-test rail as the lint, pointed at the failure.
  function carveJSON(raw) {
    let s = String(raw || '').replace(/```(?:json)?\s*/gi, '').replace(/```/g, '')
    const start = s.search(/[[{]/); if (start < 0) return null
    const open = s[start], close = open === '{' ? '}' : ']'
    let depth = 0, str = false, esc = false
    for (let i = start; i < s.length; i++) {
      const ch = s[i]
      if (esc) { esc = false; continue }
      if (ch === '\\') { esc = true; continue }
      if (ch === '"') { str = !str; continue }
      if (str) continue
      if (ch === open) depth++
      else if (ch === close && --depth === 0) return s.slice(start, i + 1)   // the brace that CLOSES it
    }
    return null
  }
