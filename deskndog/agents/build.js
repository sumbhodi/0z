// ⭐ 2026-09-01 — refresh the WHERE-TO-LOOK index on every build (Sum: "the one part of this you can
//    hand to a script and stop thinking about"). It reads the source for goalie call sites, fence tags
//    and flight-recorder paths, so the countable half of the notes can never go stale again. Chained
//    here rather than left as a command to remember: a rule nobody is stopped by scored 6 of 159.
try { require('./where-to-look.js') } catch (err) { console.log('  ⚠ where-to-look: ' + err.message) }

if (process.argv.includes('--watch')) {
  console.log('⌚ watching agents/ — edit a folder file, the bundle resyncs on its own. ctrl-c to stop.')
  let timer = null
  fs.watch(AGENTS, { recursive: true }, (_evt, file) => {
    if (!file || !file.endsWith('.json')) return          // only agent json matters
    clearTimeout(timer)
    timer = setTimeout(() => {
      try { build(); console.log('  ↻ ' + new Date().toLocaleTimeString() + '  resynced (' + file + ')') }
      catch (err) { console.log('  ⚠ ' + err.message) }
    }, 120)
  })
}
