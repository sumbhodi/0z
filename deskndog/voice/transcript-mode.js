  // ── helpers / guards ──────────────────────────────────────────────────────────────────────────────────
  function now() { return Date.now() }
  function norm(s) { return String(s == null ? '' : s).toLowerCase().replace(/[^\w\s]/g, ' ').replace(/\s+/g, ' ').trim() }
