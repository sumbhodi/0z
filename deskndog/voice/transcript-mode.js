// transcript-mode.js — MULTI-SPEAKER MEETING TRANSCRIPT mode, available for ALL bots.
//
// The always-on EAR (nurse-ear.js) is a SINGLE-USER listener: it wakes to "hello nurse", accumulates one
// person's speech, and fires snippets at the nurse. THIS module is the other shape of listening — a room
// full of people, a diarizing source that tags each utterance with a speaker label (S1/S2/…), a VERBAL,
// ALL-PARTIES consent gate, and a per-speaker-change relay to a SMART bot that cleans the raw ASR into
// flowing prose live and at the end. Any registry bot can be the smart bot ("Nurse, take notes" /
// "Toto, sit in on this"). At END it persists the whole session to window.SANDBOX as markdown + JSON.
//
// ADDITIVE — touches NOTHING in nurse-ear.js / voice.js / workspace.js / conductor.js. It COOPERATES with
// OZ_EAR two ways, best-effort, without editing it:
//   1) SOURCE SHARING — it never opens a second mic. When a session starts it calls OZ_EAR.setSource with a
//      TEE adapter that (a) forwards every event to OZ_EAR's own feed (so OZ_EAR keeps working) but (b) also
//      copies every event into THIS module's feed. On end it restores OZ_EAR's auto-source.
//   2) SINGLE-USER SUSPEND — while a transcript session is live we set OZ_EAR.config.targetBot to a throwaway
//      so its snippet sends can't collide with ours, and restore it on end. (OZ_EAR has no hard "pause", so
//      we neutralize its send target rather than edit its code.)
// If OZ_EAR is absent we still run fully off OZ_TRANSCRIPT.feed(...) — the phone source can feed us directly.
//
// DIARIZATION CONTRACT: feed({ type:'final'|'partial'|'energy'|'speechstart'|'speechend', text?, level?, speaker? }).
// A 'final' whose speaker differs from the current speaker = a SPEAKER CHANGE (finalize + relay the prior turn).
// A 'final' with NO speaker label is DROPPED by default (config.trustUntaggedContinuation=false) — a diarizer
// emits null when it can't attribute a voice (often an unknown/unconsented person), so trusting it would leak.
// START/END are DIRECT-ADDRESS commands ("[Bot], take notes" / "[Bot], meeting is over"): the bot name must be
// adjacent to the phrase, so incidental mentions ("...the meeting is over budget...") never fire.

