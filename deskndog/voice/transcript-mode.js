  // word-boundary phrase match — returns matched phrase or ''
  function wordMatch(text, phrases) {
    var w = ' ' + norm(text) + ' '
    for (var i = 0; i < phrases.length; i++) {
      var p = norm(phrases[i]); if (!p) continue
      if (w.indexOf(' ' + p + ' ') > -1) return phrases[i]
    }
    return ''
  }

  // ── REGISTRY: resolve a spoken BOT NAME → botId ───────────────────────────────────────────────────────
  function roster() {
    try { if (window.REG && Array.isArray(window.REG.agents)) return window.REG.agents } catch (_) {}
    try { if (Array.isArray(window.AGENTS_ROSTER)) return window.AGENTS_ROSTER } catch (_) {}
    return []
  }
  // find a bot whose id or label appears as a WHOLE WORD in the text. returns { id, matched } or null
  function resolveBotFromText(text) {
    var w = ' ' + norm(text) + ' '
    var list = roster()
    for (var i = 0; i < list.length; i++) {
      var a = list[i]; if (!a || !a.id) continue
      var names = [a.id, a.label].filter(Boolean)
      for (var j = 0; j < names.length; j++) {
        var n = norm(names[j]); if (!n) continue
        if (w.indexOf(' ' + n + ' ') > -1) return { id: a.id, matched: names[j] }
      }
    }
    return null
  }

  // a DIRECT-ADDRESS command: a bot name FOLLOWED (within triggerWindow words) by a trigger phrase. Rejects
  // incidental co-occurrence like "as nurse mentioned the meeting is over budget". Returns { botId, phrase } or null.
  function directCommand(text, phrases) {
    var toks = norm(text).split(' ').filter(Boolean)
    if (!toks.length) return null
    var list = roster()
    for (var bi = 0; bi < toks.length; bi++) {
      var botId = null
      for (var a = 0; a < list.length; a++) {
        var ag = list[a]; if (!ag || !ag.id) continue
        var names = [ag.id, ag.label].filter(Boolean)
        for (var n = 0; n < names.length; n++) { if (norm(names[n]) === toks[bi]) { botId = ag.id; break } }
        if (botId) break
      }
      if (!botId) continue
      var win = config.triggerWindow || 3
      for (var pi = 0; pi < phrases.length; pi++) {
        var pt = norm(phrases[pi]).split(' ').filter(Boolean); if (!pt.length) continue
        for (var st = bi + 1; st <= bi + 1 + win && st + pt.length <= toks.length; st++) {
          var ok = true
          for (var k = 0; k < pt.length; k++) { if (toks[st + k] !== pt[k]) { ok = false; break } }
          if (ok) return { botId: botId, phrase: phrases[pi] }
        }
      }
    }
    return null
  }

